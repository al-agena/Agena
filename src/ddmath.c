/* The TwoSum algorithm (Knuth 1998). Calculates the sum and resulting rounding
   error of two floating point numbers using the TwoSum algorithm. */
dd_pair two_sum (double a, double b) {
  dd_pair res;
  res.hi = a + b;
  volatile double v = res.hi - a; /* volatile forces the CPU to actually do the math */
  res.lo = (a - (res.hi - v)) + (b - v);
  return res;
}

/* Fast2Sum algorithm (Dekker 1971).
   Calculates the sum and resulting rounding error of two floating point numbers using the
   Fast2Sum algorithm. Algorithm 1 in https://doi.org/10.1145/3121432

   REQUIRES that |a| >= |b| !!!

   Taken from TwoSum C++ library */
dd_pair fast_two_sum (double a, double b) {
  dd_pair res;
  res.hi = a + b;
  double z = res.hi - a;
  res.lo = b - z;
  return res;
}

/* Calculates the difference and resulting rounding error of two floating point
   numbers using the same principle as the TwoSum algorithm.
   Taken from TwoSum C++ library */
dd_pair two_diff (double a, double b) {
  dd_pair res;
  res.hi = a - b;
  double a1 = res.hi - a;
  double b1 = res.hi - a1;
  double da = a - b1;
  double db = b + a1;
  res.lo = da - db;
  return res;
}

/* The Fast2Prod algorithm (e.g. Kahan 1996)
   Calculates the product and resulting rounding error of two floating point
   numbers using the Fast2Prod algorithm. For performance reasons, this
   algorithm should only be used if the CPU has support for fused multiply add
   (fmaf) instructions, which is not the case for most CPUs.
   Algorithm 3 in https://doi.org/10.1145/3121432
   Taken from TwoSum C++ library */
dd_pair two_prod (double a, double b) {
  dd_pair res;
  res.hi = a*b;
  res.lo = fma(a, b, -res.hi);
  return res;
}

/* Adds two double-word floating point numbers.
   We use the accurate mode (AccurateDWPlusDW in Joldes et al. (2017)),
   with the relative error always bounded.
   Taken from TwoSum C++ library */
dd_pair dd_add (dd_pair x, dd_pair y) {
  dd_pair s, t, v;
  double c, w;
  s = two_sum(x.hi, y.hi);
  t = two_sum(x.lo, y.lo);
  c = s.lo + t.hi;
  v = two_sum(s.hi, c);
  w = t.lo + v.lo;
  return two_sum(v.hi, w);  /* ensure normalisation */
}

dd_pair dd_sub (dd_pair a, dd_pair b) {
  /* Subtraction is just addition with the signs of the second operand flipped */
  dd_pair neg_b;
  neg_b.hi = -b.hi;
  neg_b.lo = -b.lo;
  return dd_add(a, neg_b);
}

dd_pair dd_mul_d (dd_pair a, double b) {
  dd_pair p = two_prod(a.hi, b);
  p.lo += a.lo*b;
  return two_sum(p.hi, p.lo);
}

dd_pair dd_mul (dd_pair x, dd_pair y) {
  /* 1. Get the high-precision product of the high parts */
  dd_pair p = two_prod(x.hi, y.hi);
  /* 2. Incorporate the cross-products of the low parts */
  /* p.lo += (x.hi*y.lo) + (x.lo*y.hi) */
  p.lo = fma(x.hi, y.lo, p.lo);
  p.lo = fma(x.lo, y.hi, p.lo);
  /* 3. Renormalize */
  return two_sum(p.hi, p.lo);  /* ensure normalisation */
}

dd_pair dd_mul_d_d (double a, double b) {
  /* No promotion needed; two_prod returns the hi and lo exactly */
  return two_prod(a, b);
}

/* Fused Multiply-Add: (a*b) + c */
dd_pair dd_fma (dd_pair a, dd_pair b, dd_pair c) {
  /* Step 1: Compute a*b exactly as a quad-double (roughly) */
  /* We start with the exact product of the high parts */
  dd_pair prod = two_prod(a.hi, b.hi);
  /* Step 2: Accumulate all cross-terms into the low part of the product */
  /* prod.lo += (a.hi*b.lo) + (a.lo*b.hi) */
  prod.lo += a.hi*b.lo;
  prod.lo += a.lo*b.hi;
  /* Step 3: Add 'c' to the product */
  /* First, add the high parts */
  dd_pair res = two_sum(prod.hi, c.hi);
  /* Step 4: Accumulate all remaining low-order components */
  /* This includes the low part of the sum, the low part of the product, */
  /* and the low part of the added pair 'c'. */
  res.lo += (prod.lo + c.lo);
  /* Step 5: Final renormalization to ensure |res.lo| <= 0.5*ulp(res.hi) */
  return two_sum(res.hi, res.lo);
}

dd_pair dd_div (dd_pair a, dd_pair b) {
  double q1 = a.hi/b.hi;
  dd_pair p1 = two_prod(q1, b.hi);
  double r_hi = a.hi - p1.hi;
  double r_lo = a.lo - p1.lo;
  r_lo -= q1*b.lo;
  double q2 = (r_hi + r_lo)/b.hi;
  return two_sum(q1, q2);
}

dd_pair dd_div_d_d (double a, double b) {
  /* Step 1: Promote doubles to dd_pair */
  dd_pair da, db;
  da.hi = a;
  da.lo = 0.0;
  db.hi = b;
  db.lo = 0.0;
  /* Step 2: Perform the double-double division */
  return dd_div(da, db);
}

dd_pair dd_inv (dd_pair a) {
  /* Step 1: Initial estimate using standard double division */
  double x0 = 1.0/a.hi;
  /* Step 2: One iteration of Newton's method: x1 = x0 + x0*(1 - a*x0) */
  /* This captures the error in the initial double-precision reciprocal */
  dd_pair ax0 = dd_mul_d(a, x0);
  /* Compute (1.0 - a*x0) accurately */
  dd_pair diff;
  diff.hi = 1.0 - ax0.hi;
  diff.lo = -ax0.lo;
  /* Correction: x0*diff */
  dd_pair corr = dd_mul_d(diff, x0);
  /* Final result: x0 + corr */
  return two_sum(x0, corr.hi + corr.lo);
}

dd_pair dd_inv_d (double a) {
  /* Step 1: Initial estimate using standard double division */
  double x0 = 1.0/a;
  /* Step 2: Refinement. Compute 1.0 - a*x0 accurately. */
  /* Since a and x0 are doubles, we use a specialized double*double->dd_pair multiplication */
  dd_pair ax0 = two_prod(a, x0);
  /* Compute (1.0 - ax0) */
  dd_pair diff;
  diff.hi = 1.0 - ax0.hi;
  diff.lo = -ax0.lo;
  /* Correction: x0*diff */
  /* Since diff is a dd_pair and x0 is a double, use dd_mul_d */
  dd_pair corr = dd_mul_d(diff, x0);
  /* Final result: x0 + corr */
  return two_sum(x0, corr.hi + corr.lo);
}

dd_pair dd_pow_n (dd_pair a, int n) {
  /* Exponentiation by squaring: O(log n) complexity */
  dd_pair res;
  res.hi = 1.0;
  res.lo = 0.0;
  if (n == 0) return res;
  /* Handle negative exponents */
  int neg = (n < 0);
  if (neg) n = -n;
  dd_pair base = a;
  while (n > 0) {
    if (n % 2 == 1) {
      res = dd_mul(res, base);
    }
    base = dd_mul(base, base);
    n /= 2;
  }
  if (neg) {
    dd_pair one;
    one.hi = 1.0;
    one.lo = 0.0;
    return dd_div(one, res);
  }
  return res;
}

dd_pair dd_pow_d_i (double a, int n) {
  /* Step 1: Promote doubles to dd_pair */
  dd_pair da;
  da.hi = a;
  da.lo = 0.0;
  /* Step 2: Perform the double-double division */
  return dd_pow_n(da, n);
}

dd_pair dd_pow (dd_pair a, dd_pair b) {  /* 7.4.1 */
  /* 1. Special Case: a^0 = 1 */
  if (b.hi == 0.0 && b.lo == 0.0) {
    return (dd_pair)DD_ONE;
  }
  /* 2. Special Case: 0^b */
  if (a.hi == 0.0 && a.lo == 0.0) {
    if (b.hi > 0.0) return (dd_pair)DD_NAUGHT;
    if (b.hi < 0.0) return (dd_pair)DD_INF;
    return (dd_pair)DD_NAN;
  }
  /* 3. Handle Negative Base 'a' */
  if (a.hi < 0.0) {
    /* a^b is only real if b is an integer */
    double b_int = sun_floor(b.hi + 0.5);
    if (b.hi == b_int && b.lo == 0.0) {
      /* Use the identity: (-a)^b = (a^b) * (-1)^b */
      dd_pair res = dd_pow(dd_neg(a), b);
      if ((int)sun_fmod(b_int, 2.0) != 0) {
        return dd_neg(res);
      }
      return res;
    }
    return (dd_pair)DD_NAN; /* Complex result not supported */
  }
  /* 4. Optimization: If b is a small exact integer, use your dd_pow_n */
  /* This is much faster and avoids log/exp overhead */
  double b_round = sun_floor(b.hi + 0.5);
  if (b.hi == b_round && b.lo == 0.0 && fabs(b_round) < 1024.0) {
    return dd_pow_n(a, (int)b_round);
  }
  /* 5. General Case: a^b = exp(b * ln(a)) */
  return dd_exp(dd_mul(b, dd_log(a)));
}

dd_pair dd_unm (dd_pair a) {
  return (dd_pair){-a.hi, -a.lo};
}

dd_pair dd_abs (dd_pair a) {
  if (a.hi < 0.0) {
    return (dd_pair){-a.hi, -a.lo};
  }
  return a;
}

dd_pair dd_absdiff (dd_pair a, dd_pair b) {
  return (dd_pair){fabs(a.hi - b.hi), fabs(a.lo - b.lo)};
}

int dd_sign (dd_pair a) {
  if (a.hi > 0.0) return 1;
  if (a.hi < 0.0) return -1;
  return 0;
}

int dd_signbit (dd_pair a) {
  /* The high part always dictates the sign of the whole pair */
  return signbit(a.hi) != 0;
}

dd_pair dd_copysign (dd_pair mag, dd_pair sgn) {
  /* We use the sign of sgn.hi and apply it to mag */
  double s = (signbit(sgn.hi)) ? -1.0 : 1.0;
  /* If the current sign doesn't match the target, flip both parts */
  if ((s < 0.0 && mag.hi >= 0.0) || (s > 0.0 && mag.hi < 0.0)) {
    return (dd_pair){-mag.hi, -mag.lo};
  }
  return mag;
}

dd_pair dd_square (dd_pair a) {
  /* Step 1: Compute the high-precision square of the hi part */
  dd_pair p = two_prod(a.hi, a.hi);
  /* Step 2: Add the cross-term: 2*a.hi*a.lo */
  /* Note: 2.0*a.hi*a.lo is equivalent to (a.hi*a.lo) + (a.hi*a.lo) */
  p.lo += 2.0*a.hi*a.lo;
  /* Step 3: Renormalize the result */
  return two_sum(p.hi, p.lo);
}

dd_pair dd_cube (dd_pair a) {
  /* Step 1: Compute a^2 with high precision */
  dd_pair a2 = dd_square(a);
  /* Step 2: Multiply by a (full dd_mul) */
  /* While we could optimize further, dd_mul(a2, a) is the most robust way
     to ensure the cross-terms are captured as the magnitude grows. */
  return dd_mul(a2, a);
}

dd_pair dd_sqrt (dd_pair a) {
  /* Step 1: Handle cases where a <= 0 */
  if (a.hi <= 0.0) {
    dd_pair res = DD_NAUGHT;
    if (a.hi < 0.0) res.hi = 0.0/0.0; /* Return NaN for negative */
    return res;
  }
  /* Step 2: Initial estimate using standard sqrt */
  double s = sqrt(a.hi);
  /* Step 3: One iteration of Newton's method: res = 0.5*(a/s + s) */
  /* We use dd_div_d_d or similar to divide our high-precision 'a' by scalar 's' */
  dd_pair a_div_s = dd_div(a, (dd_pair){s, 0.0});
  dd_pair res = dd_add(a_div_s, (dd_pair){s, 0.0});
  /* Multiply by 0.5 (which is exact in floating point) */
  res.hi *= 0.5;
  res.lo *= 0.5;
  return res;
}

dd_pair dd_cbrt (dd_pair a) {
  /* Step 1: Handle zero and special cases */
  if (a.hi == 0.0) return (dd_pair)DD_NAUGHT;
  /* Step 2: Initial estimate using standard cbrt */
  double x0 = sun_cbrt(a.hi);
  /* Step 3: Halley's Method refinement
     Formula: x1 = x0*(x0^3 + 2a)/(2x0^3 + a) */
  dd_pair x0_dd = {x0, 0.0};
  dd_pair x0_2 = dd_mul(x0_dd, x0_dd);
  dd_pair x0_3 = dd_mul(x0_2, x0_dd); /* x0^3 */
  /* Numerator: x0^3 + 2a */
  dd_pair two_a = dd_add(a, a);
  dd_pair num = dd_add(x0_3, two_a);
  /* Denominator: 2x0^3 + a */
  dd_pair two_x0_3 = dd_add(x0_3, x0_3);
  dd_pair den = dd_add(two_x0_3, a);
  /* Final refinement: x0*(num/den) */
  dd_pair ratio = dd_div(num, den);
  return dd_mul(x0_dd, ratio);
}

dd_pair dd_root_n (dd_pair a, int n) {
  /* Step 1: Handle special cases */
  if (n <= 0) return (dd_pair)DD_NAN; /* NaN */
  if (n == 1) return a;
  if (a.hi == 0.0) return (dd_pair)DD_NAUGHT;
  /* For even roots, check for negative input */
  if (n % 2 == 0 && a.hi < 0.0) return (dd_pair)DD_NAN;
  /* Step 2: Initial estimate using standard pow() */
  /* If a.hi is negative and n is odd, pow() might need help with the sign */
  double x0;
  if (a.hi < 0.0) {
    x0 = -sun_pow(-a.hi, 1.0/(double)n, 1);
  } else {
    x0 = sun_pow(a.hi, 1.0/(double)n, 1);
  }
  /* Step 3: One iteration of Newton's method */
  /* x1 = x0 + (a/x0^(n-1) - x0)/n */
  dd_pair x0_dd = {x0, 0.0};
  dd_pair x0_n_minus_1 = dd_pow_n(x0_dd, n - 1);
  dd_pair ratio = dd_div(a, x0_n_minus_1); /* a/x0^(n-1) */
  dd_pair diff = dd_sub(ratio, x0_dd);     /* (a/x0^(n-1)) - x0 */
  /* Final correction: x0 + diff/n */
  dd_pair corr = dd_mul_d(diff, 1.0/(double)n);
  return dd_add(x0_dd, corr);
}

/* High-precision Hypotenuse with coupled Newton iteration */
dd_pair dd_hypot (dd_pair a, dd_pair b) {
  /* 1. Handle special cases */
  if (a.hi == 0.0 && a.lo == 0.0) return (b.hi < 0) ? dd_neg(b) : b;
  if (b.hi == 0.0 && b.lo == 0.0) return (a.hi < 0) ? dd_neg(a) : a;
  /* 2. Compute a^2 + b^2 accurately */
  dd_pair sum2 = dd_add(dd_mul(a, a), dd_mul(b, b));
  /* 3. Initial approximation using hardware sqrt */
  double x0 = 1.0/sqrt(sum2.hi); /* We use the reciprocal sqrt for speed/accuracy */
  dd_pair h = dd_mul_d(sum2, x0);  /* h is the first estimate of sqrt(sum2) */
  /* 4. One iteration of the "coupled" Newton step:
     res = h + (sum2 - h*h) / (2 * h)
     This specific form is much more stable than 0.5 * (h + sum2/h) */
  dd_pair h2 = dd_mul(h, h);
  dd_pair diff = dd_sub(sum2, h2);
  /* Correction: diff / (2 * h) */
  double corr = (diff.hi + diff.lo)/(2.0*h.hi);
  /* 5. Final result */
  return two_sum(h.hi, h.lo + corr);
}

/* High-precision Square Root of Difference, cathetus: sqrt(a^2 - b^2) */
dd_pair dd_hypot4 (dd_pair a, dd_pair b) {
  /* 1. Handle special cases and domain validation */
  /* If |b| > |a|, the result is mathematically complex/NaN */
  if (fabs(b.hi) > fabs(a.hi)) {
    return (dd_pair){0.0/0.0, 0.0/0.0}; /* Return NaN */
  }
  /* 2. Compute a^2 - b^2 accurately */
  /* We use dd_mul and dd_sub to maintain 106-bit depth of the radicand */
  dd_pair a2 = dd_mul(a, a);
  dd_pair b2 = dd_mul(b, b);
  dd_pair diff_sq = dd_sub(a2, b2);
  /* Guard against tiny negative results due to precision limits when a == b */
  if (diff_sq.hi <= 0.0) return (dd_pair)DD_NAUGHT;
  /* 3. Initial approximation */
  double x0 = sqrt(diff_sq.hi);
  /* 4. Coupled Newton-Raphson iteration for 106-bit refinement:
     res = x0 + (diff_sq - x0^2) / (2 * x0) */
  dd_pair x0_sq = dd_mul_d((dd_pair){x0, 0.0}, x0);
  dd_pair error_term = dd_sub(diff_sq, x0_sq);
  /* Correction: error / (2 * x0) */
  double corr = (error_term.hi + error_term.lo)/(2.0*x0);
  /* 5. Final assembly */
  return two_sum(x0, corr);
}

/* Complementary Error Function: erfc(x) = 1 - erf(x) */
dd_pair dd_erfc (dd_pair x) {
  int i;
  /* 1. Handle Symmetry: erfc(-x) = 2 - erfc(x) */
  if (x.hi < 0.0) {
    dd_pair pos_erfc = dd_erfc(dd_neg(x));
    return dd_sub((dd_pair){2.0, 0.0}, pos_erfc);
  }
  /* 2. Case 1: Small x (x in [0, 1.0]) */
  /* It is more accurate to use 1 - erf(x) when x is small */
  if (x.hi <= 1.0) {
    return dd_sub((dd_pair)DD_ONE, dd_erf(x));
  }
  /* 3. Case 2: Large x (x > 1.0) */
  /* Use the Continued Fraction:
     erfc(x) = [exp(-x^2) / sqrt(pi)] * [1 / (x + (0.5 / (x + (1.0 / (x + ...)))))]
  */
  dd_pair x2 = dd_mul(x, x);
  dd_pair exp_neg_x2 = dd_exp(dd_neg(x2));
  /* Constant: 1 / sqrt(pi) */
  static const dd_pair INV_SQRT_PI = {0.56418958354775628, -2.5933010537021575e-18};
  dd_pair factor = dd_mul(exp_neg_x2, INV_SQRT_PI);
  /* Iterative evaluation of the continued fraction (Backwards) */
  /* 60 iterations are generally sufficient for 106-bit depth */
  dd_pair res = {0.0, 0.0};
  for (i=60; i > 0; i--) {
    /* res = (i * 0.5) / (x + res) */
    dd_pair num = {(double)i * 0.5, 0.0};
    dd_pair den = dd_add(x, res);
    res = dd_div(num, den);
  }
  /* final = factor / (x + res) */
  return dd_mul(factor, dd_inv(dd_add(x, res)));
}

/* Error Function: erf(x) */
dd_pair dd_erf (dd_pair x) {
  int n;
  /* Step 1: Handle Symmetry - This fixes the negative argument issue */
  if (x.hi < 0.0) {
    return dd_neg(dd_erf(dd_neg(x)));
  }
  double ax = x.hi;
  /* Case 1: Small to Medium x (Taylor Series) */
  /* We use 1.0 as the cutoff to ensure the series is fully converged */
  if (ax <= 1.0) {
    dd_pair x2 = dd_mul(x, x);
    dd_pair term = x;
    dd_pair sum = x;
    for (n=1; n < 60; n++) { /* Increased depth for 106-bit precision at x=1.0 */
      /* term = term * (-x^2) / n */
      term = dd_mul(term, x2);
      term = dd_mul_d(term, -1.0 / (double)n);

      /* current = term / (2n + 1) */
      dd_pair current = dd_mul_d(term, 1.0 / (2.0 * (double)n + 1.0));
      dd_pair next_sum = dd_add(sum, current);

      /* Check if the low part has stabilized */
      if (current.hi == 0.0 && current.lo == 0.0) break;
      if (fabs(current.hi) < fabs(sum.hi) * 1e-32) break;
      sum = next_sum;
    }
    /* erf(x) = sum * (2 / sqrt(pi)) */
    static const dd_pair TWO_OVER_SQRT_PI = {1.12837916709551257, -1.64366289567954541e-17};
    return dd_mul(sum, TWO_OVER_SQRT_PI);
  }
  /* Case 2: Large x - Use the complementary function erfc */
  /* Since x > 1.0 here, this is stable and avoids cancellation */
  return dd_sub((dd_pair)DD_ONE, dd_erfc(x));
}

