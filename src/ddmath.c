dd_pair dd_exp (dd_pair a) {
  int i;
  /* Handle large/small exponents */
  if (a.hi > 709.0) return (dd_pair)DD_INF; /* Inf */
  if (a.hi < -709.0) return (dd_pair)DD_NAUGHT;    /* 0 */
  /* 1. Find n = round(a/ln2) */
  double n = sun_floor(a.hi*DD_INV_LN2.hi + 0.5);
  /* 2. Compute r = a - n*ln2 (the remainder) */
  dd_pair x = dd_sub(a, dd_mul_d(DD_LN2, n));
  /* 3. Taylor series for e^r: 1 + r + r^2/2! + r^3/3! + r^4/4! + r^5/5! */
  /* For r < 0.35, 5-6 terms in DD math provide excellent precision */
  dd_pair x2 = dd_mul(x, x);
  dd_pair x3 = dd_mul(x2, x);
  dd_pair x4 = dd_mul(x2, x2);
  dd_pair x5 = dd_mul(x2, x3);
  dd_pair x10 = dd_mul(x5, x5);
  dd_pair x15 = dd_mul(x10, x5);
  dd_pair x20 = dd_mul(x10, x10);
  dd_pair x25 = dd_mul(x10, x15);
  dd_pair t[5] = { { 0, 0} };
  /* Coefficients */
  t[0] = dd_add((dd_pair)DD_ONE, x);
  t[1] = dd_mul(x2, inv_fact[2]);
  t[2] = dd_mul(x3, inv_fact[3]);
  t[3] = dd_mul(x4, inv_fact[4]);
  /* Sum the series: 1.0 + r + r^2/2 + r^3/6 + r^4/24 */
  /* z = x + inv_fact[2]*x2 + inv_fact[3]*x3 + inv_fact[4]*x4 */
  dd_pair z = (dd_pair){ 0.0, 0.0 };
  for (i=0; i < 4; i++) {
    z = dd_add(z, t[i]);
  }
  /* z2 = x5*(inv_fact[5] + x*inv_fact[6] + x2*inv_fact[7] +
     x3*inv_fact[8] + x4*inv_fact[9]) */
  t[0] = inv_fact[5];
  t[1] = dd_mul(x, inv_fact[6]);
  t[2] = dd_mul(x2, inv_fact[7]);
  t[3] = dd_mul(x3, inv_fact[8]);
  t[4] = dd_mul(x4, inv_fact[9]);
  dd_pair z2 = (dd_pair){ 0.0, 0.0 };
  for (i=0; i < 5; i++) {
    z2 = dd_add(z2, t[i]);
  }
  z2 = dd_mul(x5, z2);
  /* z3 = x10*(inv_fact[10] + x*inv_fact[11] + x2*inv_fact[12] +
     x3*inv_fact[13] + x4*inv_fact[14]) */
  t[0] = inv_fact[10];
  t[1] = dd_mul(x, inv_fact[11]);
  t[2] = dd_mul(x2, inv_fact[12]);
  t[3] = dd_mul(x3, inv_fact[13]);
  t[4] = dd_mul(x4, inv_fact[14]);
  dd_pair z3 = (dd_pair){ 0.0, 0.0 };
  for (i=0; i < 5; i++) {
    z3 = dd_add(z3, t[i]);
  }
  z3 = dd_mul(x10, z3);
  /* z4 = x15*(inv_fact[15] + x*inv_fact[16] + x2*inv_fact[17] +
     x3*inv_fact[18] + x4*inv_fact[19]) */
  t[0] = inv_fact[15];
  t[1] = dd_mul(x, inv_fact[16]);
  t[2] = dd_mul(x2, inv_fact[17]);
  t[3] = dd_mul(x3, inv_fact[18]);
  t[4] = dd_mul(x4, inv_fact[19]);
  dd_pair z4 = (dd_pair){ 0.0, 0.0 };
  for (i=0; i < 5; i++) {
    z4 = dd_add(z4, t[i]);
  }
  z4 = dd_mul(x15, z4);
  /* z5 = x20*(inv_fact[20] + x*inv_fact[21] + x2*inv_fact[22] +
     x3*inv_fact[23] + x4*inv_fact[24]) */
  t[0] = inv_fact[20];
  t[1] = dd_mul(x, inv_fact[21]);
  t[2] = dd_mul(x2, inv_fact[22]);
  t[3] = dd_mul(x3, inv_fact[23]);
  t[4] = dd_mul(x4, inv_fact[24]);
  dd_pair z5 = (dd_pair){ 0.0, 0.0 };
  for (i=0; i < 5; i++) {
    z5 = dd_add(z5, t[i]);
  }
  z5 = dd_mul(x20, z5);
  /* z6 = x25*(inv_fact[25] + x*inv_fact[26] + x2*inv_fact[27]) */
  t[0] = inv_fact[25];
  t[1] = dd_mul(x, inv_fact[26]);
  t[2] = dd_mul(x2, inv_fact[27]);
  dd_pair z6 = (dd_pair){ 0.0, 0.0 };
  for (i=0; i < 3; i++) {
    z6 = dd_add(z6, t[i]);
  }
  z6 = dd_mul(x25, z6);
  /* ((((z6+z5)+z4)+z3)+z2)+z + one(DoubleFloat{T}) (for one see above */
  t[0] = dd_add(z6, z5);
  t[0] = dd_add(t[0], z4);
  t[0] = dd_add(t[0], z3);
  t[0] = dd_add(t[0], z2);
  z = dd_add(t[0], z);
  /* 4. Scale by 2^n */
  z.hi = sun_ldexp(z.hi, (int)n);
  z.lo = sun_ldexp(z.lo, (int)n);
  return z;
}

/* exp2(x) = 2^x = e^(x * ln2), 7.4.1 */
dd_pair dd_exp2 (dd_pair a) {
  /* we do not use: return dd_exp(dd_mul(a, DD_LN2)); */
  /* 1. Handle overflow/underflow boundaries for 64-bit doubles */
  if (a.hi > 1023.0) return (dd_pair)DD_INF;
  if (a.hi < -1074.0) return (dd_pair)DD_NAUGHT;
  /* 2. Extract integer part n and fractional part r */
  /* 2^a = 2^n * 2^r */
  double n = sun_floor(a.hi + 0.5);
  dd_pair r = dd_sub(a, (dd_pair){n, 0.0});
  /* 3. Compute 2^r using e^(r * ln2) */
  /* Because |r| <= 0.5, the Taylor series is at its most accurate */
  dd_pair e_r = dd_exp(dd_mul(r, DD_LN2));
  /* 4. Scale by 2^n using ldexp */
  /* This is a lossless operation for both hi and lo parts */
  e_r.hi = sun_ldexp(e_r.hi, (int)n);
  e_r.lo = sun_ldexp(e_r.lo, (int)n);
  return e_r;
}

/* exp10(x) = 10^x = e^(x * ln10), 7.4.1 */
dd_pair dd_exp10 (dd_pair a) {
  /* return dd_exp(dd_mul(a, DD_LN10)); is too inaccurate */
  /* 1. Handle large/small exponents */
  if (a.hi > 308.0) return (dd_pair)DD_INF;
  if (a.hi < -308.0) return (dd_pair)DD_NAUGHT;
  /* 2. Decompose a into integer and fractional parts: 10^a = 10^n * 10^r */
  double n = sun_floor(a.hi + 0.5);
  dd_pair r = dd_sub(a, (dd_pair){n, 0.0});
  /* 3. Compute 10^r using 10^r = e^(r * ln10) */
  /* Since r is now very small (-0.5 to 0.5), the Taylor series is extremely stable */
  dd_pair r_ln10 = dd_mul(r, DD_LN10);
  dd_pair e_r = dd_exp(r_ln10);
  /* 4. Scale by 10^n */
  /* We use pow(10, n) for the high part and then perform a clean dd multiplication */
  dd_pair scale = {(double)sun_pow(10.0, n, 1), 0.0};
  return dd_mul(e_r, scale);
}

dd_pair dd_log (dd_pair a) {
  if (a.hi <= 0.0) return (dd_pair)DD_NAN;
  /* 1. Initial guess */
  double x0 = sun_log(a.hi);
  /* 2. Refinement: x1 = x0 + (a - exp(x0))/exp(x0) */
  dd_pair ex0 = dd_exp((dd_pair){x0, 0.0});
  dd_pair diff = dd_sub(a, ex0);
  dd_pair corr = dd_div(diff, ex0);
  return dd_add((dd_pair){x0, 0.0}, corr);
}

dd_pair dd_log2 (dd_pair a) {
  /* Step 1: Handle non-positive inputs */
  if (a.hi <= 0.0) return (dd_pair)DD_NAN;
  /* Step 2: Change of base formula: log2(a) = ln(a)/ln(2) */
  /* Using your previously defined dd_log and DD_LN2 constant */
  return dd_div(dd_log(a), DD_LN2);
}

dd_pair dd_log10 (dd_pair a) {  /* 7.4.1 */
  /* Step 1: Handle non-positive inputs */
  if (a.hi <= 0.0) return (dd_pair)DD_NAN;
  /* Step 2: Change of base formula: log10(a) = ln(a)/ln(10) */
  /* We use the pre-defined dd_log and the high-precision DD_LN10 constant */
  return dd_div(dd_log(a), DD_LN10);
}

dd_pair dd_sin (dd_pair a) {
  /* 1. Argument reduction */
  double k_double = sun_floor(a.hi*DD_INV_PI_2.hi + 0.5);
  int i, k = (int)k_double;
  dd_pair r = dd_sub(a, dd_mul_d(DD_PI_2, k_double));
  dd_pair r2 = dd_mul(r, r);
  /* 2. Taylor series: Horner evaluation */
  dd_pair s_res = (dd_pair)DD_ONE;
  for (i=25; i >= 3; i -= 2) {
    dd_pair term = dd_mul(r2, s_res);
    /* Divide dd_pair by dd_pair to maintain 106-bit precision */
    dd_pair divisor = (dd_pair){(double)(i*(i - 1)), 0.0};
    dd_pair divided_term = dd_div(term, divisor);
    s_res = dd_sub(DD_ONE, divided_term);
  }
  dd_pair sin_r = dd_mul(r, s_res);
  /* cos(r) Horner */
  dd_pair c_res = (dd_pair)DD_ONE;
  for (i=26; i >= 2; i -= 2) {
    dd_pair term = dd_mul(r2, c_res);
    dd_pair divisor = (dd_pair){(double)(i*(i - 1)), 0.0};
    dd_pair divided_term = dd_div(term, divisor);
    c_res = dd_sub(DD_ONE, divided_term);
  }
  dd_pair cos_r = c_res;
  /* 3. Selection */
  dd_pair res;
  switch (k & 3) {
    case 0:  res = sin_r; break;
    case 1:  res = cos_r; break;
    case 2:  res = (dd_pair){-sin_r.hi, -sin_r.lo}; break;
    case 3:  res = (dd_pair){-cos_r.hi, -cos_r.lo}; break;
    default: res = sin_r; break;
  }
  return res;
}

dd_pair dd_cos (dd_pair a) {
  double k_double = sun_floor(a.hi*DD_INV_PI_2.hi + 0.5);
  int i, k = (int)k_double;
  dd_pair r = dd_sub(a, dd_mul_d(DD_PI_2, k_double));
  dd_pair r2 = dd_mul(r, r);
  /* sin(r) Horner */
  dd_pair s_res = (dd_pair)DD_ONE;
  for (i=25; i >= 3; i -= 2) {
    dd_pair term = dd_mul(r2, s_res);
    dd_pair divisor = (dd_pair){(double)(i*(i - 1)), 0.0};
    dd_pair divided_term = dd_div(term, divisor);
    s_res = dd_sub((dd_pair)DD_ONE, divided_term);
  }
  dd_pair sin_r = dd_mul(r, s_res);
  /* cos(r) Horner */
  dd_pair c_res = (dd_pair)DD_ONE;
  for (i=26; i >= 2; i -= 2) {
    dd_pair term = dd_mul(r2, c_res);
    dd_pair divisor = (dd_pair){(double)(i*(i - 1)), 0.0};
    dd_pair divided_term = dd_div(term, divisor);
    c_res = dd_sub((dd_pair)DD_ONE, divided_term);
  }
  dd_pair cos_r = c_res;
  dd_pair res;
  switch (k & 3) {
    case 0:  res = cos_r; break;
    case 1:  res = (dd_pair){-sin_r.hi, -sin_r.lo}; break;
    case 2:  res = (dd_pair){-cos_r.hi, -cos_r.lo}; break;
    case 3:  res = sin_r; break;
    default: res = cos_r; break;
  }
  return res;
}

dd_pair dd_tan (dd_pair a) {
  /* Reuse the reduction and Taylor logic from dd_sin/dd_cos */
  /* This is a simplified wrapper for brevity */
  dd_pair s = dd_sin(a);
  dd_pair c = dd_cos(a);
  return dd_div(s, c);
}

/* Secant: 1/cos(a) */
dd_pair dd_sec (dd_pair a) {
  dd_pair cos_a = dd_cos(a);
  /* Use the reciprocal logic: 1.0/cos_a */
  return dd_inv(cos_a);
}

/* Cosecant: 1/sin(a) */
dd_pair dd_csc (dd_pair a) {
  dd_pair sin_a = dd_sin(a);
  /* Use the reciprocal logic: 1.0/sin_a */
  return dd_inv(sin_a);
}

/* Cotangent: cos(a)/sin(a) */
dd_pair dd_cot (dd_pair a) {
  dd_pair s = dd_sin(a);
  dd_pair c = dd_cos(a);
  /* Manual dd_div(c, s) logic for maximum precision */
  /* Step 1: Approximate quotient */
  double q0 = c.hi/s.hi;
  /* Step 2: Refine using: q1 = q0 + (c - s*q0)/s */
  dd_pair sq0 = dd_mul_d(s, q0);
  /* Compute remainder: diff = c - sq0 */
  dd_pair diff = dd_sub(c, sq0);
  /* Correction term: diff/s.hi (approximate is fine for the tail) */
  double corr = (diff.hi + diff.lo)/s.hi;
  /* Final result */
  if (dd_signbit(a)) corr = -corr;
  return two_sum(q0, corr);
}

dd_pair dd_sinc (dd_pair x) {
  double abs_x = (x.hi < 0) ? -x.hi : x.hi;
  /* Taylor series for small x to avoid precision loss and division by zero.
     The threshold 1e-4 is safe for maintaining ~31 decimal digits. */
  if (abs_x < 1e-4) {
    /* sinc(x) = 1 - x^2/6 + x^4/120 - x^6/5040 ... */
    dd_pair x2 = dd_mul(x, x);
    /* Term 1: 1.0 */
    dd_pair res = DD_ONE;
    /* Term 2: -x^2/6 */
    dd_pair term2 = dd_mul_d(x2, -1.0/6.0);
    res = dd_add(res, term2);
    /* Term 3: x^4/120 */
    dd_pair x4 = dd_mul(x2, x2);
    dd_pair term3 = dd_mul_d(x4, 1.0/120.0);
    res = dd_add(res, term3);
    /* Term 4: -x^6/5040 (Optional but recommended for 106-bit depth) */
    dd_pair x6 = dd_mul(x4, x2);
    dd_pair term4 = dd_mul_d(x6, -1.0/5040.0);
    res = dd_add(res, term4);
    return res;
  }
  /* Standard case: sin(x)/x */
  dd_pair s = dd_sin(x);
  /* Use the high-precision division refinement */
  double q0 = s.hi/x.hi;
  dd_pair xq0 = dd_mul_d(x, q0);
  dd_pair diff = dd_sub(s, xq0);
  double corr = (diff.hi + diff.lo)/x.hi;
  return two_sum(q0, corr);
}

dd_pair dd_sinh (dd_pair x) {
  /* Guard against overflow (matches Julia's maxhyp_fp64max) */
  if (fabs(x.hi) > 710.47) {
    return (dd_pair){(x.hi > 0) ? 1.0/0.0 : -1.0/0.0, 0.0};
  }
  /* signbit(x) && return -sinh(-x) */
  if (x.hi < 0.0) {
    dd_pair res = dd_sinh((dd_pair){-x.hi, -x.lo});
    return (dd_pair){-res.hi, -res.lo};
  }
  /* y = exp(x) - exp(-x) */
  dd_pair exp_x = dd_exp(x);
  dd_pair exp_neg_x = dd_inv(exp_x);
  dd_pair y = dd_sub(exp_x, exp_neg_x);
  /* z = y*0.5 */
  return (dd_pair){y.hi*0.5, y.lo*0.5};
}

dd_pair dd_cosh (dd_pair x) {
  if (fabs(x.hi) > 710.47) return (dd_pair)DD_INF;
  /* cosh(x) is symmetric, so we can work with absolute value */
  dd_pair abs_x = (x.hi < 0.0) ? (dd_pair){-x.hi, -x.lo} : x;
  /* y = exp(x) + exp(-x) */
  dd_pair exp_x = dd_exp(abs_x);
  dd_pair exp_neg_x = dd_inv(exp_x);
  dd_pair y = dd_add(exp_x, exp_neg_x);
  return (dd_pair){y.hi*0.5, y.lo*0.5};
}

dd_pair dd_tanh (dd_pair x) {
  /* For large x, tanh approaches 1 or -1 */
  if (fabs(x.hi) > 20.0) { /* 20 is enough for 106-bit saturation */
    return (x.hi > 0) ? (dd_pair)DD_ONE : (dd_pair){-1.0, 0.0};
  }
  return dd_div(dd_sinh(x), dd_cosh(x));
}

/* Hyperbolic Secant: 1/cosh(a) */
dd_pair dd_sech (dd_pair a) {
  dd_pair cosh_a = dd_cosh(a);
  return dd_inv(cosh_a);
}

/* Hyperbolic Cosecant: 1/sinh(a) */
dd_pair dd_csch (dd_pair a) {
  dd_pair sinh_a = dd_sinh(a);
  return dd_inv(sinh_a);
}

/* Hyperbolic Cotangent: cosh(a)/sinh(a) */
dd_pair dd_coth (dd_pair a) {
  /* Using the same refined division logic as dd_cot */
  dd_pair s = dd_sinh(a);
  dd_pair c = dd_cosh(a);
  /* Step 1: Approximate quotient */
  double q0 = c.hi/s.hi;
  /* Step 2: Refinement: q1 = q0 + (c - s*q0)/s */
  dd_pair sq0 = dd_mul_d(s, q0);
  dd_pair diff = dd_sub(c, sq0);
  /* Correction term */
  double corr = (diff.hi + diff.lo)/s.hi;
  return two_sum(q0, corr);
}

dd_pair dd_atan2 (dd_pair y, dd_pair x);

dd_pair dd_atan (dd_pair x) {
  /* Using the atan2 logic: atan(x) = atan2(x, 1) */
  return dd_atan2(x, (dd_pair)DD_ONE);
}

dd_pair dd_asin (dd_pair x) {
  /* Check for domain errors */
  if (x.hi > 1.0 || x.hi < -1.0) return DD_NAN;
  /* asin(x) = atan2(x, sqrt(1 - x^2)) */
  dd_pair x2 = dd_mul(x, x);
  dd_pair root = dd_sqrt(dd_sub((dd_pair)DD_ONE, x2));
  return dd_atan2(x, root);
}

dd_pair dd_acos (dd_pair x) {
  /* Check for domain errors */
  if (x.hi > 1.0 || x.hi < -1.0) return DD_NAN;
  /* acos(x) = atan2(sqrt(1 - x^2), x) */
  dd_pair x2 = dd_mul(x, x);
  dd_pair root = dd_sqrt(dd_sub((dd_pair)DD_ONE, x2));
  return dd_atan2(root, x);
}

