dd_pair dd_pair_from_d (double d) {
  dd_pair res;
  res.hi = d;
  res.lo = 0.0;
  return res;
}

dd_pair dd_lgamma (dd_pair x) {
  int i;
  /* Use the identity Gamma(x+1) = x*Gamma(x) if x is small */
  /* For lgamma: ln(Gamma(x)) = ln(Gamma(x+1)) - ln(x) */
  double y = dd2double(x);
  if (y == 1.0) {
    return (dd_pair)DD_ONE;
  } else if (y <= 0) {
    return (dd_pair)DD_NAN;
  }
  dd_pair tmp = dd_add(x, dd_pair_from_d(5.5)); /* x + g + 0.5 */
  /* (x + 0.5)*ln(tmp) */
  dd_pair log_part = dd_mul(dd_add(x, DD_HALF), dd_log(tmp));
  /* Summing Ag(x) */
  dd_pair a = LY[0];
  for (i=1; i < 7; i++) {
    dd_pair denom = dd_add(x, dd_pair_from_d((double)i));
    a = dd_add(a, dd_div(LY[i], denom));
  }
  /* ln(sqrt(2*pi)*a/x) */
  /* dd_pair sqrt2pi = dd_pair_from_d(2.5066282746310005); */
  dd_pair final_ln = dd_log(dd_div(dd_mul(DD_SQRT_2PI, a), x));
  /* Result = log_part - tmp + final_ln */
  return dd_add(dd_sub(log_part, tmp), final_ln);
}

/* Note that 170! is the largest factorial that fits in a standard double range (1.7×10^308). */
dd_pair dd_fac (dd_pair a) {
  int i;
  /* 1. Handle Negative Arguments */
  if (a.hi < 0.0) return (dd_pair)DD_NAN;
  /* 2. Exact Integer Case (up to ~30 for speed) */
  /* We check if it's an integer by comparing the double part to its cast */
  if (a.lo == 0.0 && a.hi <= 30.0 && a.hi == (double)((int)a.hi)) {
    int n = (int)a.hi;
    if (n == 0) return (dd_pair)DD_NAN;
    dd_pair res = DD_ONE;
    for (i=2; i <= n; i++) {
      res = dd_mul_d(res, (double)i);
    }
    return res;
  }
  /* 3. General Case: Gamma(a + 1) */
  /* We manually create a dd_pair for 1.0 to use the standard dd_add */
  /* dd_pair one = DD_ONE; */
  dd_pair a_plus_one = dd_add(a, DD_ONE);
  /* Ensure these functions exist in your ddmath.h */
  return dd_exp(dd_lgamma(a_plus_one));
}

dd_pair dd_floor (dd_pair a) {
  double hi = floor(a.hi);
  double lo = 0.0;
  if (hi == a.hi) {
    /* If the high part is an integer, the low part determines the floor */
    lo = sun_floor(a.lo);
    /* Re-normalize: if lo is -1.0, it affects the high part */
    return two_sum(hi, lo);
  }
  return (dd_pair){hi, 0.0};
}

dd_pair dd_ceil (dd_pair a) {
  double hi = ceil(a.hi);
  double lo = 0.0;
  if (hi == a.hi) {
    /* If the high part is an integer, the low part determines the ceil */
    lo = sun_ceil(a.lo);
    /* Re-normalize: if lo is 1.0, it affects the high part */
    return two_sum(hi, lo);
  }
  return (dd_pair){hi, 0.0};
}

/* round to nearest integer */
dd_pair dd_round (dd_pair a) {
  double hi = sun_round(a.hi);
  if (hi == a.hi) {
    /* High part is an integer, check low part to see if it nudges the result */
    double lo = sun_round(a.lo);
    return two_sum(hi, lo);
  }
  /* Check if a.lo was enough to push a.hi across a midpoint boundary */
  /* This happens if a.hi was something like 2.4999... and a.lo pushed it to 2.5 */
  double diff = a.hi - hi;
  if (fabs(diff) == 0.5 && ((diff > 0 && a.lo < 0) || (diff < 0 && a.lo > 0))) {
     /* Re-evaluate if the tail changed the rounding direction */
     return dd_round(two_sum(a.hi, a.lo));
  }
  return (dd_pair){hi, 0.0};
}

/* trunc toward Zero */
dd_pair dd_trunc (dd_pair a) {
  return (a.hi >= 0.0) ? dd_floor(a) : dd_ceil(a);
}

dd_pair dd_frac (dd_pair a) {
  /* frac = a - floor(a) */
  return dd_sub(a, dd_trunc(a));
}

dd_pair dd_modf (dd_pair a, dd_pair *iptr) {
  /* Store the integer part in the provided pointer */
  *iptr = dd_trunc(a);
  /* Return the fractional part */
  return dd_sub(a, *iptr);
}

/* renorm (Internal Precision Rounding): Sometimes "rounding" refers to the internal
   process of ensuring the hi and lo parts are as "separated" as possible.
   While your two_sum and two_prod functions handle this automatically, a dedicated
   renormalization ensures that. */
dd_pair dd_renorm (double hi, double lo) {
  /* This is effectively a robust two_sum */
  double s = hi + lo;
  double v = s - hi;
  double e = (hi - (s - v)) + (lo - v);
  return (dd_pair){s, e};
}

dd_pair dd_ldexp (dd_pair a, int e) {
  /* We scale both parts by the same power of 2 */
  /* This preserves the relative gap between hi and lo */
  return (dd_pair){
    sun_ldexp(a.hi, e),
    sun_ldexp(a.lo, e)
  };
}

dd_pair dd_frexp (dd_pair a, int *e) {
  /* 1. Decompose the high part to get the exponent */
  double f_hi = sun_frexp(a.hi, e);
  /* 2. Scale the low part by the SAME exponent to keep them aligned */
  /* We use negative *exp because we are 'unscaling' the value */
  double f_lo = sun_ldexp(a.lo, -(*e));

  return (dd_pair){f_hi, f_lo};
}


/* Printing function: Since this uses a static buffer, you must use it immediately or copy it:

   WRONG: Both will point to the same string (the value of b)
   const char* str_a = dd_to_str(a);
   const char* str_b = dd_to_str(b);
   printf("%s %s", str_a, str_b);

   CORRECT:
   printf("Value A: %s\n", dd_to_str(a));
   printf("Value B: %s\n", dd_to_str(b)); */
const char *dd_to_str (dd_pair a) {
  static char buffer[128];
  int i, decimal_exp;
  if (isinf(a.hi) || isnan(a.hi)) {
    sprintf(buffer, "%g", a.hi);
    return buffer;
  }
  if (a.hi == 0.0 && a.lo == 0.0)
    return "0.0000000000000000000000000000000e+00";
  /* 1. Calculate exponent */
  decimal_exp = (int)floor(log10(fabs(a.hi + a.lo)));
  /* 2. Scale the value to [1, 10) */
  dd_pair scaled = dd_mul(a, dd_pow_n((dd_pair){10.0, 0.0}, -decimal_exp));
  /* 3. Handle negative numbers */
  int pos = 0;
  if (scaled.hi < 0 || (scaled.hi == 0 && scaled.lo < 0)) {
    buffer[pos++] = '-';
    scaled.hi = -scaled.hi;
    scaled.lo = -scaled.lo;
  }
  /* 4. The Extraction Loop */
  for (i = 0; i < 32; i++) {
    /* 1. Extract the digit using the combined weight */
    double val = scaled.hi + scaled.lo;
    int digit = (int)floor(val + 1e-14);
    if (digit > 9) digit = 9;
    if (digit < 0) digit = 0;
    buffer[pos++] = (char)('0' + digit);
    if (i == 0) buffer[pos++] = '.';
    /* 2. MANUAL SUBTRACTION - Do not rely on dd_sub for now */
    /* This ensures the lo part isn't dropped by a bad metamethod/function */
    double t_hi = scaled.hi - (double)digit;
    double t_lo = scaled.lo;
    /* 3. RENORMALIZE - This is the key */
    /* It pulls the high-precision 'remainder' back into the hi double */
    scaled.hi = t_hi + t_lo;
    scaled.lo = t_lo - (scaled.hi - t_hi);
    /* 4. SHIFT - Pull the next bits up */
    /* Use your dd_mul_d or do it manually to be safe */
    double m_hi = scaled.hi*10.0;
    double m_lo = scaled.lo*10.0;
    scaled.hi = m_hi + m_lo;
    scaled.lo = m_lo - (scaled.hi - m_hi);
  }
  sprintf(buffer + pos, "e%+03d", decimal_exp);
  return buffer;
}

int dd_eq (dd_pair a, dd_pair b) {
  return (a.hi == b.hi && a.lo == b.lo);
}

int dd_lt (dd_pair a, dd_pair b) {
  return (a.hi < b.hi || (a.hi == b.hi && a.lo < b.lo));
}

int dd_gt (dd_pair a, dd_pair b) {
  return (a.hi > b.hi || (a.hi == b.hi && a.lo > b.lo));
}

int dd_le (dd_pair a, dd_pair b) {
  return (a.hi < b.hi || (a.hi == b.hi && a.lo <= b.lo));
}

int dd_ge (dd_pair a, dd_pair b) {
  return (a.hi > b.hi || (a.hi == b.hi && a.lo >= b.lo));
}

int dd_approx (dd_pair x, dd_pair y, dd_pair eps) {
  /* 1. Identity and NaN check */
  if ((x.hi == y.hi && x.lo == y.lo) || (isnan(x.hi) && isnan(y.hi))) {
    return 1;
  }
  /* 2. Calculate absolute distance |x - y| */
  dd_pair dist = dd_abs(dd_sub(x, y));
  /* 3. Infinite distance check (overflow in subtraction) */
  if (isinf(dist.hi)) return 0;
  /* 4. Absolute tolerance check: dist <= eps */
  if (dd_le(dist, eps)) return 1;
  /* 5. Relative tolerance check: dist <= eps*max(|x|, |y|) */
  dd_pair abs_x = dd_abs(x);
  dd_pair abs_y = dd_abs(y);
  dd_pair max_val = dd_gt(abs_x, abs_y) ? abs_x : abs_y;
  dd_pair rel_tol = dd_mul(eps, max_val);
  return dd_le(dist, rel_tol);
}

