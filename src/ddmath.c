static const dd_pair DD_INV_4f  = {  4.16666666666666644e-02,  2.31296463463574266e-19 };
static const dd_pair DD_INV_5f  = {  8.33333333333333322e-03,  1.15740740740740731e-19 };
static const dd_pair DD_INV_6f  = { -1.38888888888888884e-03, -1.92901234567901219e-21 };
static const dd_pair DD_INV_7f  = { -1.98412698412698413e-04, -1.25816434460596323e-21 };
static const dd_pair DD_INV_8f  = {  2.48015873015873016e-05,  1.57270543075745404e-23 };
static const dd_pair DD_INV_9f  = {  2.75573192239858907e-06,  1.23330105370215750e-23 };
static const dd_pair DD_INV_10f = { -2.75573192239858907e-07, -1.23330105370215750e-25 };
static const dd_pair DD_INV_11f = { -2.50521083854417188e-08, -6.64322477382215714e-26 };
static const dd_pair DD_INV_12f = {  2.08767569878680990e-09,  5.53602064485179762e-27 };
static const dd_pair DD_INV_13f = {  1.60590438368216146e-10,  1.25055964894318182e-28 };
static const dd_pair DD_INV_14f = { -2.05885177395148906e-12, -4.38536294717112285e-30 };
static const dd_pair DD_INV_15f = { -7.64716373181981648e-13, -3.24794712850383178e-30 };

static dd_pair dd_pi_reduce (dd_pair theta, int *k) {
  double k_double = floor(theta.hi * TWOOPI + 0.5);
  *k = (int)k_double;
  /* Three-stage reduction for 106-bit stability */
  dd_pair r = dd_sub(theta, two_prod(k_double, PI2_HI));
  r = dd_sub(r, two_prod(k_double, PI2_LO));
  r = dd_sub(r, (dd_pair){k_double * PI2_LO2, 0.0}); /* Final tail correction */
  return r;
}

void dd_sincos (dd_pair theta, dd_pair *s, dd_pair *c) {
  int k;
  dd_pair r = dd_pi_reduce(theta, &k);
  /* Precompute powers to r^15 */
  dd_pair r2 = dd_mul(r, r);
  dd_pair r3 = dd_mul(r, r2);
  dd_pair r4 = dd_mul(r2, r2);
  dd_pair r5 = dd_mul(r3, r2);
  dd_pair r6 = dd_mul(r4, r2);
  dd_pair r7 = dd_mul(r5, r2);
  dd_pair r8 = dd_mul(r6, r2);
  dd_pair r9 = dd_mul(r7, r2);
  dd_pair r10 = dd_mul(r8, r2);
  dd_pair r11 = dd_mul(r9, r2);
  dd_pair r12 = dd_mul(r10, r2);
  dd_pair r13 = dd_mul(r11, r2);
  dd_pair r14 = dd_mul(r12, r2);
  dd_pair r15 = dd_mul(r13, r2);
  /* Sine Series Expansion (r^1 to r^15) */
  dd_pair s_tail = dd_mul(r15, DD_INV_15f);
  s_tail = dd_add(s_tail, dd_mul(r13, DD_INV_13f));
  s_tail = dd_add(s_tail, dd_mul(r11, DD_INV_11f));
  s_tail = dd_add(s_tail, dd_mul(r9,  DD_INV_9f));
  s_tail = dd_add(s_tail, dd_mul(r7,  DD_INV_7f));
  s_tail = dd_add(s_tail, dd_mul(r5,  DD_INV_5f));
  s_tail = dd_add(s_tail, dd_mul(r3,  DD_INV_3f));
  dd_pair s_res = dd_add(r, s_tail);
  /* Cosine Series Expansion (r^0 to r^14) */
  dd_pair c_tail = dd_mul(r14, DD_INV_14f);
  c_tail = dd_add(c_tail, dd_mul(r12, DD_INV_12f));
  c_tail = dd_add(c_tail, dd_mul(r10, DD_INV_10f));
  c_tail = dd_add(c_tail, dd_mul(r8,  DD_INV_8f));
  c_tail = dd_add(c_tail, dd_mul(r6,  DD_INV_6f));
  c_tail = dd_add(c_tail, dd_mul(r4,  DD_INV_4f));
  c_tail = dd_add(c_tail, dd_mul(r2,  DD_INV_2f));
  dd_pair c_res = dd_add((dd_pair){1.0, 0.0}, c_tail);
  /* Map to correct quadrant */
  switch (k & 3) {
    case 0: *s = s_res;         *c = c_res;         break;
    case 1: *s = c_res;         *c = dd_neg(s_res); break;
    case 2: *s = dd_neg(s_res); *c = dd_neg(c_res); break;
    case 3: *s = dd_neg(c_res); *c = s_res;         break;
  }
}

dd_pair dd_atan2 (dd_pair y, dd_pair x) {
  int i;
  /* 1. Handle the origin */
  if (x.hi == 0.0 && y.hi == 0.0) return DD_ZERO;
  /* 2. Record the signs for later reconstruction */
  int sign_x = (x.hi < 0) ? -1 : 1;
  int sign_y = (y.hi < 0) ? -1 : 1;
  /* 3. Force everything into the First Quadrant (0 to pi/2) */
  dd_pair abs_x = (x.hi < 0) ? dd_neg(x) : x;
  dd_pair abs_y = (y.hi < 0) ? dd_neg(y) : y;
  /* 4. Use your stable Newton-Raphson on the 'safe' positive values */
  /* We use the ratio to get the initial estimate */
  double t0 = sun_atan2(abs_y.hi, abs_x.hi);
  dd_pair theta = {t0, 0.0};
  for (i=0; i < 3; i++) {
    dd_pair s = dd_sin(theta);
    dd_pair c = dd_cos(theta);
    /* Corrected stable formula for the 1st quadrant: */
    /* num = abs_y*c - abs_x*s, den = abs_x*c + abs_y*s */
    dd_pair num = dd_sub(dd_mul(abs_y, c), dd_mul(abs_x, s));
    dd_pair den = dd_add(dd_mul(abs_x, c), dd_mul(abs_y, s));
    if (den.hi == 0.0) break;
    dd_pair corr = dd_div(num, den);
    theta = dd_add(theta, corr);
    if (sun_fabs(corr.hi) < sun_fabs(theta.hi)*1e-32) break;
  }
  /* 5. Reconstruction Logic (Symmetry Mapping) */
  /* If x was negative, we are in Quadrant 2 or 3: angle = PI - angle */
  if (sign_x < 0) {
    theta = dd_sub(DD_PI, theta);
  }
  /* If y was negative, flip the final sign (Odd Function Symmetry) */
  if (sign_y < 0) {
    theta = dd_neg(theta);
  }
  return theta;
}

/* Inverse Secant: acos(1/a) */
dd_pair dd_asec (dd_pair a) {
  /* Step 1: Compute reciprocal of the argument */
  dd_pair inv_a = dd_inv(a);
  /* Step 2: Use the identity asec(x) = acos(1/x) */
  return dd_acos(inv_a);
}

/* Inverse Cosecant: asin(1/a) */
dd_pair dd_acsc (dd_pair a) {
  /* Step 1: Compute reciprocal of the argument */
  dd_pair inv_a = dd_inv(a);
  /* Step 2: Use the identity acsc(x) = asin(1/x) */
  return dd_asin(inv_a);
}

/* Inverse Cotangent: atan(1/a) */
dd_pair dd_acot (dd_pair a) {
  /* Handle the singularity at 0 directly for stability */
  if (a.hi == 0.0) {
    return dd_mul_d(DD_PI, 0.5); /* pi/2 */
  }
  dd_pair inv_a = dd_inv(a);
  dd_pair res = dd_atan(inv_a);
  /* If a is negative, shift the result by PI to stay in the (0, pi) range */
  if (a.hi < 0.0) {
    res = dd_add(res, DD_PI);
  }
  return res;
}

