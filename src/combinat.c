static long double bernoulli_number (int n, lua_Number eps) {  /* 7.6.4 */
  int k, m;
  long double r1, r2, s;
  switch (n) {
    case 0:
      return 1.0L;
    case 1:
      return -0.5L;
    case 2:
      return ONESIXTHld;
    default: {
      if (n < 0) return AGN_NAN;
      if (n & 1) {  /* bernoulli(odd integer) = 0 */
        return 0.0L;
      }
      r1 = ONEoPISQUAREDld;
      r2 = 0.0L;
      for (m=4; m <= n; m += 2) {
        r1 = -r1*(m - 1)*m/PI2SQUAREDld;  /* PI2SQUARED = PI2 * PI2 */
        r2 = 1.0L;
        s  = 10000.0L;  /* 3.5.6 change */
        for (k=2; s >= eps && k <= 10000; k++) {
          s = tools_powil(1.0L/k, m);  /* tuned 2.29.5 */
          r2 += s;
        }
      }
      return r1*r2;  /* <=> bn(m) = r1 * r2 */
    }
  }
}

static long double bernoulli_poly (int n, lua_Number x, lua_Number eps) {  /* 7.7.4, generated by Gemini AI */
  int k;
  long double sum = 0.0L;
  for (k=0; k <= n; k++) {
    long double xk = (k == 0 && fabsl(x) < 1e-10L) ? 1.0L : tools_powl(x, k);
    sum += tools_binomiall(n, k)*bernoulli_number(n - k, eps)*xk;
  }
  return sum;
}


static long double euler_number (int n, lua_Number eps) {
  int k, m;
  switch (n) {
    case 0:
      return 1.0L;
    case 2:
      return -1.0L;
      break;
    default: {
      long double r, r1, r2, s, isgn;
      if (n < 0) return AGN_NAN;
      if (n & 1) {  /* euler(odd integer) = 0 */
        r = 0.0L;
      } else if (n <= EULER_NUMBERS_SIZE) {  /* 2.41.0 extension */
        r = euler_numbers[n >> 1];
      } else {
        r1 = -4.0*TWOoPICUBEDld;
        r2 = 0.0;
        for (m=4; m <= n; m += 2) {
          r1 = - r1*(m - 1)*m*TWOoPISQUAREDld;  /* 0.405.. =  TWOoPI* TWOoPI */
          r2 = 1.0;
          isgn = 1.0;
          for (k=3; k <= 1000; k += 2) {
            isgn = -isgn;
            s = tools_powil(1.0/k, m + 1);  /* tuned 2.29.5 */
            r2 = r2 + isgn*s;
            if (s < eps) break;
          }
        }
        r = r1*r2;  /* <=> bn(m) = r1 * r2 */
      }
      return r;
    }
  }
}

static long double euler_poly (int n, long double x, long double eps) {  /* 7.7.4, generated by Elon's Grok */
  int k;
  if (n == 0) return 1.0L;
  long double sum = 0.0L;
  long double xmhalf = x - 0.5L;
  for (k=0; k <= n; k++) {
    long double xk;
    if (fabsl(xmhalf) < 1e-10L) {  /* safe check instead of exact == */
      xk = (k == 0) ? 1.0L : 0.0L;
    } else {
      xk = tools_powl(xmhalf, k);
    }
    sum += tools_binomiall(n, k) * euler_number(n - k, eps) * xk / tools_powl(2.0L, n - k);
  }
  return sum;
}

