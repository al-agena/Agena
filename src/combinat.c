static void aux_checkeboptions (lua_State *L, int pos, int *nargs, lua_Number *eps, const char *procname) {  /* new 7.7.4 */
  *eps = agn_getdblepsilon(L);
  int checkoptions = 1;  /* check n options; CHANGE THIS if you add/delete options */
  if (*nargs >= pos && lua_ispair(L, *nargs))
    luaL_checkstack(L, 2, "not enough stack space");
  while (checkoptions-- && *nargs >= pos && lua_ispair(L, *nargs)) {
    agn_pairgeti(L, *nargs, 1);  /* get left value, set to stack index -2 */
    agn_pairgeti(L, *nargs, 2);  /* get right value, set to stack index  -1 */
    if (agn_isstring(L, -2)) {
      const char *option = agn_tostring(L, -2);
      if (tools_streq(option, "eps")) {
        *eps = agn_checkpositive(L, -1);
      } else {
        agn_poptoptwo(L);
        luaL_error(L, "Error in " LUA_QS ": unknown option " LUA_QS ".", procname, option);
      }
    }
    /* do not call lua_settop as it would corrupt the argument stack since we have already pushed values */
    (*nargs)--;
    agn_poptoptwo(L);
  }
}


/* Returns the n-th Bell number, i.e. counts the possible partitions of a set. 2.22.1,
   See: https://www.geeksforgeeks.org/bell-numbers-number-of-ways-to-partition-a-set/
   Rewritten 7.3.4 to prevent C stack corruption, reduce memory consumption from O(n^2)
   to O(n), by Gemini AI, put to the public domain. */

static int stirling2 (int n, int k);

static long double bell_poly (int n, long double x) {
  int k;
  long double sum = 0.0L;
  long double p = x;
  if (n <= 0) return x == 0 ? 0.0L : 1.0L;  /* do like Maple V Release 4 does */
  for (k=1; k <= n; k++) {
    sum += stirling2(n, k) * p;
    p *= x;
  }
  return sum;
}

static int combinat_bell (lua_State *L) {
  int i, j, n;
  lua_Number *row, current_val, prev_val;
  n = agn_checknonnegint(L, 1);
  if (n > 218) {
    lua_pushnumber(L, HUGE_VAL);
    return 1;
  }
  if (lua_gettop(L) > 1) {
    long double x = agn_checknumber(L, 2);
    lua_pushnumber(L, bell_poly(n, x));
    return 1;
  }
  row = (lua_Number *)malloc((n + 1) * sizeof(lua_Number));
  if (!row)
    luaL_error(L, "Error in " LUA_QS ": memory allocation failed.", "combinat.bell");
  row[0] = 1;
  for (i=1; i <= n; i++) {
    /* The Aitken's Triangle rule: The first element of row 'i' is the last element of row 'i-1' */
    prev_val = row[i - 1];
    for (j=0; j < i; j++) {
      current_val = row[j];
      row[j] = prev_val;
      prev_val += current_val;
    }
  row[i] = prev_val;
  }
  /* Result is the first element of the N-th row */
  lua_pushnumber(L, row[0]);
  xfree(row);
  return 1;
}


/* Gemini AI: "The Narayana polynomials Nn(x) are indeed considered the standard polynomial
   generalization of the Catalan numbers. 7.7.4, generated by Gemini AI. */

static long double narayana (int n, long double x) {
  int k;
  long double sum = 0.0L;
  if (n <= 0) return AGN_NAN;
  long double px = 1.0L;
  for (k=1; k <= n; k++) {
    long double b1 = (long double)(tools_binomiall(n, k));
    long double b2 = (long double)(tools_binomiall(n, k - 1));
    px *= x;
    sum += b1*b2*px/(long double)(n);
  }
  return sum;
}

static int combinat_catalan (lua_State *L) {  /* 3.7.0 */
  int n = agn_checknonnegint(L, 1);
  if (lua_gettop(L) == 1) {
    lua_pushnumber(L, tools_binomial(2*n, n)/(n + 1));
  } else {  /* Catalan polynomial, 7.7.4 */
    long double x = agn_checknumber(L, 2);
    lua_pushnumber(L, narayana(n, x));
  }
  return 1;
}


