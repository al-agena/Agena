/* --- Initialize --- */
DoubleHashSet *dhs_create (size_t initial_capacity, int optimised) {
  /* Ensure capacity is at least 8 or the next power of 2 */
  size_t cap = 8;
  while (cap < initial_capacity) cap <<= 1;
  DoubleHashSet *set = malloc(sizeof(DoubleHashSet));
  if (!set) return NULL;
  set->keys = malloc(cap * sizeof(double));
  if (!set->keys) return NULL;
  set->status = calloc(cap, sizeof(SlotStatus));
  if (!set->status) return NULL;
  set->capacity = cap;
  set->count = 0;
  set->optimised = optimised;
  return set;
}


/* Faster than modulo: maps a 64-bit hash to [0, capacity), 6.5.12 by Gemini AI:
   Portable 32-bit reduction (works on almost any C compiler) */
static inline uint32_t aux_reduce32 (uint32_t x, uint32_t N) {
  return (uint32_t)(((uint64_t)x * (uint64_t)N) >> 32);
}

#define aux_getidx(set, h_val) ({ \
  size_t _idx; \
  if ((set)->optimised) \
    _idx = ((uint64_t)(h_val)) & ((set)->capacity - 1); \
  else \
    _idx = aux_reduce32((uint32_t)(h_val), (uint32_t)(set)->capacity); \
  (_idx); \
})

/* --- Internal: Resize/Rehash --- */
static int dhs_resize_to_size (DoubleHashSet *set, size_t new_cap) {
  size_t i, idx, old_cap = set->capacity;
  double *old_keys = set->keys;
  SlotStatus *old_status = set->status;
  /* 1. Allocate new arrays with the specific new capacity */
  double *new_keys = malloc(new_cap * sizeof(double));
  if (new_keys == NULL) return 0;
  /* calloc clears the new status array, setting all slots to DBLHASH_EMPTY */
  SlotStatus *new_status = calloc(new_cap, sizeof(SlotStatus));
  if (new_status == NULL) {
    xfree(new_keys);
    return 0;
  }
  /* 2. Temporarily update the set to the new dimensions */
  set->keys = new_keys;
  set->status = new_status;
  set->capacity = new_cap;
  set->count = 0; /* Reset count; we will increment it as we re-insert */
  /* 3. Re-hash ONLY the occupied items into the new space */
  for (i=0; i < old_cap; i++) {
    if (old_status[i] == DBLHASH_OCCUPIED) {
      uint64_t h = dhs_hash(old_keys[i]);
      idx = aux_getidx(set, h);
      /* Probing in the new table (no tombstones exist yet) */
      while (set->status[idx] == DBLHASH_OCCUPIED) {
        idx++;
        if (idx >= set->capacity) idx = 0;
      }
      set->keys[idx] = old_keys[i];
      set->status[idx] = DBLHASH_OCCUPIED;
      set->count++;
    }
  }
  /* 4. Free the old memory buffers */
  /* Assuming xfreeall is your cleanup macro */
  xfreeall(old_keys, old_status);
  return 1;
}


/* --- Insert --- */
int dhs_insert (DoubleHashSet *set, double val) {
  size_t idx, first_deleted_idx, insert_pos;
  /* Check Load Factor: Grow if > 70% */
  if ((double)set->count / set->capacity > 0.7) {
    size_t new_cap = set->optimised ? (set->capacity << 1) : tools_nextprime(agn_newsize(NULL, set->capacity));
    if (dhs_resize_to_size(set, new_cap) == 0) return 0;
  }
  uint64_t h = dhs_hash(val);
  idx = aux_getidx(set, h);
  first_deleted_idx = (size_t)-1;
  while (set->status[idx] != DBLHASH_EMPTY) {
    if (set->status[idx] == DBLHASH_OCCUPIED) {
      if (set->keys[idx] == val) return 1; /* Already exists */
    }  else if (set->status[idx] == DBLHASH_DELETED) {
      if (first_deleted_idx == (size_t)-1) first_deleted_idx = idx;
    }
    idx++;
    if (idx >= set->capacity) idx = 0;
  }
  insert_pos = (first_deleted_idx != (size_t)-1) ? first_deleted_idx : idx;
  set->keys[insert_pos] = val;
  set->status[insert_pos] = DBLHASH_OCCUPIED;
  set->count++;
  return 1;
}

/* --- Search --- */
bool dhs_contains (DoubleHashSet *set, double val) {
  uint64_t h = dhs_hash(val);
  size_t idx = aux_getidx(set, h);
  /* We loop until we hit an DBLHASH_EMPTY slot */
  while (set->status[idx] != DBLHASH_EMPTY) {
    if (set->status[idx] == DBLHASH_OCCUPIED && set->keys[idx] == val) return true;
    /* Linear Probing: increment and wrap */
    idx++;
    if (idx >= set->capacity) idx = 0;
  }
  return false;
}

/* --- removal --- */
static int dhs_shrink (DoubleHashSet *set) {
  /* Calculate new capacity: usually half of current */
  size_t new_cap;
  if (set->optimised) {
    new_cap = set->capacity >> 1;
  } else {
    /* In memory-saving mode, aim for a prime that results in roughly 40-50% load factor */
    new_cap = tools_nextprime(set->count * 2);
  }
  /* Safety: Don't shrink below a reasonable minimum */
  if (new_cap < 8) return 1;
  /* We can simply call our existing resize logic but with the smaller size */
  /* Note: You may need to tweak your dhs_resize to accept 'new_cap' as an argument */
  return dhs_resize_to_size(set, new_cap);
}

bool dhs_remove (DoubleHashSet *set, double val, int shrink) {
  uint64_t h = dhs_hash(val);
  size_t idx = aux_getidx(set, h);
  /* Search the probe chain */
  while (set->status[idx] != DBLHASH_EMPTY) {
    if (set->status[idx] == DBLHASH_OCCUPIED && set->keys[idx] == val) {
      /* 1. Remove the item */
      set->status[idx] = DBLHASH_DELETED;
      set->count--;
      /* 2. Check for downsizing */
      /* Threshold: Shrink if capacity > 16 and load factor < 12.5% */
      if (shrink && set->capacity > 16 && (double)set->count / set->capacity < 0.125) {
        /* We don't return false if shrinking fails;  the removal was still successful. */
        dhs_shrink(set);
      }
      return true;
    }
    /* Move to the next slot (Linear Probing) */
    idx++;
    if (idx >= set->capacity) idx = 0;
  }
  return false; /* Key not found */
}

void dhs_free (DoubleHashSet *set) {
  xfreeall(set->keys, set->status, set);
}

/* --- Helpers --- */

static size_t dhs_getfirstpossibleidx (DoubleHashSet *set, double val) {
  uint64_t h = dhs_hash(val);
  return aux_getidx(set, h);
}

size_t dhs_getidx (DoubleHashSet *set, double val, int *rc) {
  uint64_t h = dhs_hash(val);
  size_t idx = aux_getidx(set, h);
  *rc = 0; /* Default to not found */
  /* Loop until we hit an DBLHASH_EMPTY slot */
  while (set->status[idx] != DBLHASH_EMPTY) {
    if (set->status[idx] == DBLHASH_OCCUPIED && set->keys[idx] == val) {
      *rc = 1;      /* Found it! */
      return idx;   /* Return the actual position */
    }
    /* Consistent Linear Probing */
    idx++;
    if (idx >= set->capacity) idx = 0;
  }
  return (size_t)-1; /* Return sentinel to indicate not found */
}


