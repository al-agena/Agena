static int dblhash_getitem (lua_State *L) {
  int nargs;
  int64_t idx;
  nargs = lua_gettop(L);
  DoubleHashSet *u = checkdblhash(L, 1);
  if (nargs == 1) {
    lua_getfenv(L, 1);
    return 1;
  }
  luaL_checkstack(L, 2, "not enough stack space");
  idx = agn_checkinteger(L, 2);  /* 7.3.9 fix */
  if (idx >= 0 && idx < u->capacity) {
    if (u->status[idx] == DBLHASH_EMPTY) {
      lua_pushnil(L);
      lua_pushliteral(L, "empty");
    } else {
      lua_pushnumber(L, u->keys[idx]);
      lua_pushstring(L, (u->status[idx] == DBLHASH_OCCUPIED) ? "occupied" : "deleted");
    }
  } else {
    luaL_error(L, "Error in " LUA_QS ": index %d out of range.", "dblhash.getitem", idx);
  }
  return 2;
}


/* Returns the actual index number x is stored in double hash table d, plus the index position where
   x could have been stored if it would not have been already occupied by another value (or itself).
   The indices returned start from 0. If d would have to be resized before inserting x, then the function
   returns `null` twice. If the first result is `null` and the second an integer n, it means that x is not
   part of d but could be stored to position n in the hash table if it were vacant.

   See also: dblhash.getitem. */
static int dblhash_getindex (lua_State *L) {
  size_t idx;
  int rc;
  DoubleHashSet *u = checkdblhash(L, 1);
  lua_Number x = agn_checknumber(L, 2);
  luaL_checkstack(L, 2, "not enough stack space");
  if ((double)u->count/u->capacity > 0.7) {
    lua_pushnil(L);
    lua_pushnil(L);
  } else {
    idx = dhs_getidx(u, x, &rc);
    if (!rc) {
      lua_pushnil(L);
    } else {
      lua_pushnumber(L, idx);
    }
    lua_pushnumber(L, dhs_getfirstpossibleidx(u, x));
  }
  return 2;
}


static int iterate (lua_State *L) {
  DoubleHashSet *u = lua_touserdata(L, lua_upvalueindex(1));
  int idx = lua_tointeger(L, lua_upvalueindex(2));
  if (idx >= u->capacity) {
    lua_pushnil(L);
    return 1;
  }
  luaL_checkstack(L, 2, "not enough stack space");
  for (; idx < u->capacity; idx++) {
    if (u->status[idx] == DBLHASH_OCCUPIED) {
      lua_pushnumber(L, u->keys[idx]);
      lua_pushinteger(L, (int)idx + 1);
      lua_replace(L, lua_upvalueindex(2));
      return 1;
    }
  }
  lua_pushnil(L);
  return 1;
}

