static int dblhash_attrib (lua_State *L) {
  DoubleHashSet *u = checkdblhash(L, 1);
  size_t i, deleted_count = 0;
  /* Count tombstones (slots with deleted data) to report table health */
  for (i=0; i < u->capacity; i++) {
    if (u->status[i] == DBLHASH_DELETED) deleted_count++;
  }
  lua_createtable(L, 0, 6);
  lua_rawsetstringnumber(L, -1,  "count",       (double)u->count);
  lua_rawsetstringnumber(L, -1,  "capacity",    (double)u->capacity);
  lua_rawsetstringboolean(L, -1, "optimised",   u->optimised);
  /* New Health Stats */
  lua_rawsetstringnumber(L, -1,  "deleted",     (double)deleted_count);  /* tombstones */
  lua_rawsetstringnumber(L, -1,  "loadfactor",  (double)u->count/u->capacity);
  lua_rawsetstringnumber(L, -1,  "utilization", (double)(u->count + deleted_count)/u->capacity);
  return 1;
}


/* Returns the high and lower unsigned 32-bit words of the SplitMix64-based hash for number x. 6.5.11 */
static int dblhash_hash (lua_State *L) {
  uint64_t h;
  uint32_t n, hx, lx, cx;
  lua_Number x = agn_checknumber(L, 1);
  n = agnL_optuint32_t(L, 2, 0);
  h = dhs_hash(x);
  luaL_checkstack(L, 3, "not enough stack space");
  hx = (uint32_t)(h >> 32);          /* high */
  lx = (uint32_t)(h & 0xFFFFFFFFU);  /* low */
  cx = hx ^ lx;  /* high and low combined, equal to (uint32_t)(h ^ (h >> 32)) */
  if (n == 0) {
    /* return raw 32-bit unsigned integers */
    lua_pushnumber(L, (lua_Number)hx);
    lua_pushnumber(L, (lua_Number)lx);
    lua_pushnumber(L, (lua_Number)cx);
  } else {
    /* return values constrained to [0, n-1] */
    lua_pushnumber(L, (lua_Number)(hx % n));
    lua_pushnumber(L, (lua_Number)(lx % n));
    lua_pushnumber(L, (lua_Number)(cx % n));
  }
  return 3;
}


/* Returns all active numbers in double hash table d in a new sequence. The result is not sorted. Values
   previously deleted but still available will not be returned. */
static int dblhash_toseq (lua_State *L) {  /* 6.5.12 */
  int64_t idx, c;
  DoubleHashSet *u = checkdblhash(L, 1);
  agn_createseq(L, u->count);
  c = 1;
  for (idx=0; idx < u->capacity; idx++) {
    if (u->status[idx] == DBLHASH_OCCUPIED) {
      agn_seqsetinumber(L, -1, c++, u->keys[idx]);
    }
  }
  return 1;
}


