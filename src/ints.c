/* RNG, as proposed by Gemini AI, put into the public domain.

   Features:
   - Simplicity and Speed: The core next_u64 function is very short, relying only on basic bitwise (XOR, shift, rotate)
     and addition operations, making it extremely fast.

   - Quality: It passes most standard statistical tests (like TestU01's BigCrush) well, though it is not cryptographically
     secure.

   - State: The internal state is crucial. It must be a non-zero value. The provided seed_from_single_u64 function handles
     generating a robust two-word seed from a single input like time(NULL).

   - Period: The period is huge, meaning it can generate a vast number of unique random numbers before repeating the sequence. */

/* State variables (must be seeded to a non-zero state) */
static uint64_t s[2] = { 0 };

/* Function to generate the next 64-bit random number */
static uint64_t next_u64 (void) {
  const uint64_t s0 = s[0];
  uint64_t s1 = s[1];
  /* The result is the sum of the two state words */
  const uint64_t result = s0 + s1;
  /* Update the state using XOR, rotation, and shift operations */
  s1 ^= s0;
  s[0] = rotl(s0, 24) ^ s1 ^ (s1 << 16);  /* a=24, b=16 */
  s[1] = rotl(s1, 37);                    /* c=37 */
  return result;
}

