/**
 * Raises base to the power of exponent (base^exponent) for uint64_t.
 *
 * @param base The uint64_t base.
 * @param exponent The non-negative integer exponent.
 * @param result Pointer to store the result.
 * @return True if the calculation succeeded without overflow, false otherwise.
 *
 * Created by Gemini AI, public domain.
 */
static bool power_uint64 (uint64_t base, int exponent, uint64_t *result) {
  *result = 1;  /* Start with result = base^0 = 1 */
  if (exponent < 0) return false;  /* Technically undefined for integers, treat as an error */
  if (exponent == 0) return true;  /* base^0 = 1 */
  if (base == 0) {
    *result = 0;
    return true;  /* 0^E = 0 for E > 0 */
  }
  /* --- Core Binary Exponentiation Loop --- */
  uint64_t current_base = base;
  /* Iterate through the bits of the exponent */
  while (exponent > 0) {
    /* Check if the current bit of the exponent is 1 (exponent is odd) */
    if (exponent & 1) {
      /* Check for multiplication overflow: *result * current_base */
      if (current_base > UINT64_MAX / *result) return false;  /* Overflow occurred */
      *result *= current_base;
    }
    /* Prepare for the next bit of the exponent (exponent is divided by 2) */
    exponent >>= 1;
    /* If exponent is now 0, stop to avoid squaring unnecessarily */
    if (exponent == 0) break;
    /* Check for squaring overflow: current_base * current_base */
    if (current_base > UINT64_MAX / current_base) return false;  /* Overflow occurred during squaring */
    current_base *= current_base;
  }
  return true;  /* Success */
}

/**
 * Raises base to the power of exponent (base^exponent) for int64_t.
 *
 * @param base The int64_t base.
 * @param exponent The integer exponent.
 * @param result Pointer to store the result.
 * @return True if the calculation succeeded without signed overflow, false otherwise.
 *
 * Created by Gemini AI, public domain.
 */
static bool power_int64 (int64_t base, int exponent, int64_t *result) {
  /* 1. Handle special cases based on exponent */
  if (exponent < 0) {
    /* Integer power function typically handles only non-negative exponents.
       For negative exponents, the result is fractional (e.g., 2^-1 = 0.5),
       which cannot be represented as an int64_t (except for 0). */
    if (exponent == 0) *result = 1;  /* Base case for non-zero base */
    else *result = 0;  /* Truncated result for 1/base^|exponent| */
    return true;  /* We return 0, which is technically the floor of the result */
  }
  if (exponent == 0) {
    *result = 1;  /* base^0 = 1 */
    return true;
  }
  if (base == 0) {
    *result = 0;
    return true;  /* 0^E = 0 for E > 0 */
  }
  if (base == 1) {
    *result = 1;
    return true;
  }
  /* 2. Determine the sign of the final result
     The sign depends on the base and the exponent's parity. */
  bool final_sign_is_negative = (base < 0) && (exponent % 2 != 0);
  /* 3. Use absolute value for the main calculation
     This simplifies overflow checks, as we only check against INT64_MAX. */
  uint64_t abs_base = abs64(base);  /* 6.2.1/2, on some systems there is no llabs. */
  uint64_t abs_result_u = 1;
  /* --- Core Binary Exponentiation Loop on unsigned values --- */
  uint64_t current_base = abs_base;
  while (exponent > 0) {
    if (exponent & 1) {
      /* Check for multiplication overflow: abs_result_u * current_base
         If the required result exceeds the positive limit (INT64_MAX), it overflows. */
      if (current_base > (uint64_t)INT64_MAX / abs_result_u) {
        return false;  /* Positive overflow */
      }
      abs_result_u *= current_base;
    }
    exponent >>= 1;
    if (exponent == 0) break;
    /* Check for squaring overflow: current_base * current_base */
    if (current_base > (uint64_t)INT64_MAX / current_base) {
      return false;  /* Positive overflow during squaring */
    }
    current_base *= current_base;
  }
  /* 4. Apply the final sign */
  if (final_sign_is_negative) {
    /* Check for the negative overflow case: INT64_MIN.
       The maximum positive result (INT64_MAX) is 1 smaller than the
       magnitude of the minimum negative result (INT64_MIN).
       Since abs_result_u holds the magnitude, if abs_result_u > INT64_MAX,
       the result is too large to fit in the negative range, *unless*
       abs_result_u is exactly 9223372036854775808 (INT64_MAX + 1), which
       corresponds to INT64_MIN. */
    if (abs_result_u == (uint64_t)INT64_MIN) {
      *result = INT64_MIN;
    } else if (abs_result_u > (uint64_t)INT64_MAX) {
      return false;  /* Overflow (magnitude too large) */
    } else {
      *result = -(int64_t)abs_result_u;
    }
  } else {
    /* Positive result */
    if (abs_result_u > (uint64_t)INT64_MAX) {
      return false;  /* Positive overflow */
    }
    *result = (int64_t)abs_result_u;
  }
  return true;
}

