/* Safely converts a string to a uint64_t. Generated by Gemini AI, public domain. */
static uint64_t safe_str_to_uint64 (const char *str, int *rc) {
  char *endptr;
  uint64_t result;
  const char *oldstr = str;
  if (str == NULL) { *rc = 4; return 0; }
  *rc = 0;
  /* 1. Reset errno to 0 before the call to distinguish between  successful execution and error conditions. */
  errno = 0;
  /* 2. Perform the conversion using base 10 (decimal). */
  result = strtoull(str, &endptr, 10);
  /* 3A. Check for underflow/overflow (result out of range). If the result equals ULLONG_MAX (UINT64_MAX) AND
         errno is ERANGE, an overflow/underflow occurred. */
  if (errno == ERANGE) {  /* fprintf(stderr, "Error: Value out of range for uint64_t.\n"); */
    *rc = 1; return 0;
  }
  /* 3B. Check for no conversion (input was not a number)
         If endptr points to the start of the string, no digits were processed. */
  if (endptr == str) {  /* fprintf(stderr, "Error: No digits were found in the string.\n"); */
    *rc = 2; return 0;
  }
  /* 3C. Check for extraneous characters (non-numeric data after the number)
         The string should be fully consumed (endptr should point to the null terminator). */
  if (*endptr != '\0') {  /* try hex string */
    int r;
    lua_State *L = NULL;
    result = lua_stringtouint64(L, oldstr, 0, NULL, &r);
    if (r) {  /* fprintf(stderr, "Error: Invalid character(s) found after the number: %s\n", endptr); */
      *rc = r; return 0;
    }
  }
  return result;
}

