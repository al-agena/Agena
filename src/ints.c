/* builds a number with 'n' ones (1 <= n <= LUA_NBITS) */
#define mask64(n)    (~((ALLONES64 << 1) << ((n) - 1)))

/* Counts the number of trailing zeros (ctz) in the unsigned 64-bit integer x, and also
   returns the modified value of x after this operation as a second result, where all bits
   starting with the least significant bit in x are set to 1. 6.2.1 */
