/* Generated by Gemini AI, put into the public domain. 10.29.2025
   A helper function to implement the Extended Euclidean Algorithm (EEA).
   It calculates: a*x + m*y = gcd(a, m)
   It returns the gcd, and updates x and y to hold the coefficients.
   Note: The EEA naturally returns signed coefficients (x, y), even for unsigned inputs. */
static uint64_t aux_gcdu64 (uint64_t a, uint64_t m, int64_t *x, int64_t *y) {
  if (a == 0ULL) {
    *x = 0LL; *y = 1LL; return m;
  }
  /* Recursive step */
  int64_t x1, y1;
  uint64_t gcd = aux_gcdu64(m % a, a, &x1, &y1);
  /* Update x and y using results from recursive call */
  *x = y1 - (int64_t)(m/a)*x1;
  *y = x1;
  return gcd;
}

/* Generated by Gemini AI, put into the public domain. 10.29.2025
   Calculates the modular multiplicative inverse of 'a' modulo 'm'.
   Returns 'x' such that a*x === 1 (mod m).
   Returns 0 if the inverse does not exist (gcd(a, m) != 1) or if m is 0/1. */
uint64_t modinverseu64 (uint64_t a, uint64_t m) {
  int64_t x, y, a_mod, gcd, m_signed, inv_signed;
  if (m <= 1ULL) return 0ULL;
  /* 1. Calculate a mod m */
  a_mod = a % m;
  /* Edge case: 0 has no inverse mod m (unless m=1, which is checked above) */
  if (a_mod == 0ULL) return 0ULL;
  /* 2. Compute GCD and the coefficient x */
  gcd = aux_gcdu64(a_mod, m, &x, &y);
  /* 3. Check if the inverse exists */
  if (gcd != 1ULL) return 0ULL;  /* Inverse does not exist (a and m are not coprime) */
  /* 4. Adjust x to be in the positive range [1, m-1]
        The result 'x' is a signed integer from EEA. We must map it back to
        the unsigned [1, m-1] range using modular arithmetic.
        Cast m to signed for the operation, then adjust if negative */
  m_signed = (int64_t)m;
  inv_signed = x % m_signed;
  if (inv_signed < 0LL) inv_signed += m_signed;
  return (uint64_t)inv_signed;
}

static int64_t aux_gcdi64 (int64_t a, int64_t m, int64_t *x, int64_t *y) {
  int64_t x1, y1, gcd;
  if (a == 0LL) {
    *x = 0LL; *y = 1LL; return m;
  }
  /* Recursive step */
  gcd = aux_gcdi64(m % a, a, &x1, &y1);
  /* Update x and y using results from recursive call */
  *x = y1 - (m/a)*x1;
  *y = x1;
  return gcd;
}

/* Calculates the modular multiplicative inverse of 'a' modulo 'm'.
   Returns 'x' such that a*x === 1 (mod m).
   Returns 0 if the inverse does not exist (gcd(a, m) != 1). */
static int64_t modinverse64 (int64_t a, int64_t m) {
  if (m <= 0LL) return 0LL;
  int64_t x, y, a_mod, gcd, inv;
  /* 1. Ensure 'a' is in the canonical positive range [0, m-1] */
  a_mod = a % m;
  if (a_mod < 0LL) a_mod += m;
  /* Edge case: if a_mod is 0, the inverse does not exist (unless m=1) */
  if (a_mod == 0LL) return 0LL;
  /* 2. Compute GCD and the coefficient x */
  gcd = aux_gcdi64(a_mod, m, &x, &y);
  /* 3. Check if the inverse exists */
  if (gcd != 1LL) return 0LL;  /* Inverse does not exist (a and m are not coprime) */
  /* 4. Adjust x to be in the positive range [1, m-1]
        The EEA guarantees that 'x' is the solution, but it might be negative. */
  inv = x % m;
  if (inv < 0LL) inv += m;
  return inv;
}

