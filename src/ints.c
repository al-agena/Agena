static uint64_t power_u64 (uint64_t base, uint32_t expo) {
  uint32_t i;
  uint64_t res = 1;
  for (i=0; i < expo; i++) {
    /* check if res * base would exceed 64 bits */
    if (res > 0 && base > (0xFFFFFFFFFFFFFFFFULL/res)) {
      return 0xFFFFFFFFFFFFFFFFULL;  /* return MAX if it would overflow */
    }
    res *= base;
  }
  return res;
}

static int64_t nth_root_i64 (int64_t v, int n, int *rc) {
  uint64_t x, y, p;
  *rc = 0;
  if (n <= 0) { *rc = -1; return 0; }  /* undefined for nonposints */
  if (n == 1) return v;
  if (v == 0) return 0;
  if (v < 0) {
    if (n % 2 == 0) { *rc = -1; return 0; }  /* no real root for even n */
    return -nth_root_i64(-v, n, rc);
  }
  /* 1. Initial Guess: log2(v)/n gives a very close starting bit */
  x = 1ULL << ((64 - __builtin_clzll((uint64_t)v))/n + 1);
  /* 2. Newton-Raphson Iteration */
  while (1) {
    /* We need x^(n-1) */
    p = power_u64(x, n - 1);
    if (p == 0xFFFFFFFFFFFFFFFFULL) {
      *rc = -2;  /* overflow */
      return 0LL;
    }
    /* Apply the general Newton formula */
    y = ((n - 1)*x + (uint64_t)v/p)/n;
    if (y >= x) return (int64_t)x;
    x = y;
  }
}

static uint64_t nth_root_ui64 (uint64_t v, int n, int *rc) {
  uint64_t x, y, p;
  *rc = 0;
  if (n <= 0) { *rc = -1; return 0; }  /* undefined for nonposints */
  if (n == 1) return v;
  if (v == 0) return 0;
  /* 1. Initial Guess: log2(v)/n gives a very close starting bit */
  x = 1ULL << ((64 - __builtin_clzll(v))/n + 1);
  /* 2. Newton-Raphson Iteration */
  while (1) {
    /* We need x^(n-1) */
    p = power_u64(x, n - 1);
    if (p == 0xFFFFFFFFFFFFFFFFULL) {
      *rc = -2;  /* overflow */
      return 0ULL;
    }
    /* Apply the general Newton formula */
    y = ((n - 1)*x + v/p)/n;
    if (y >= x) return x;
    x = y;
  }
}

