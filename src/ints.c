static int ints_touint64 (lua_State *L) {
  if (isints(L, 1)) {
    Ints *a = (Ints *)lua_touserdata(L, 1);
    if (a->datatype == INT64T) {  /* cast to uint64_t */
      createuint64(L, (uint64_t)a->data.i);
    } else {  /* just return input */
      lua_settop(L, 1);
    }
  } else {
    createbitwiseintfromdouble(L, UINT64T, agn_checknumber(L, 1), "ints.touint64");
  }
  return 1;
}


