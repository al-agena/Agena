static int ints_todouble (lua_State *L) {
  Ints *a = checkints(L, 1);
  switch (a->datatype) {
    case UINT64T: {
      lua_pushnumber(L, bitwiseuint64todouble(a->data.ui));
      break;
    }
    case INT64T: {
      lua_pushnumber(L, bitwiseint64todouble(a->data.i));
      break;
    }
    default:
      luaL_error(L, "Error in " LUA_QS ": datatype %d is not supported.", "ints.todouble", a->datatype);
  }
  return 1;
}


static int ints_getstore (lua_State *L) {
  int nargs = lua_gettop(L);
  checkints(L, 1);
  if (nargs == 1) {
    lua_getfenv(L, 1);
  } else if (agn_isinteger(L, 2)) {
    lua_getfenvi(L, 1, agn_tointeger(L, 2));
  } else {
    lua_getfenv(L, 1);
    lua_replace(L, 1);
    lua_settop(L, 2);
    lua_rawget(L, 1);
  }
  return 1;
}


static int ints_tonumber (lua_State *L) {
  Ints *a = checkints(L, 1);
  luaL_checkstack(L, 2, "not enough stack space");
  switch (a->datatype) {
    case UINT64T: {
      uint64_t x = a->data.ui;
      lua_pushnumber(L, x);
      lua_pushboolean(L, x > DBL_MAX);
      break;
    }
    case INT64T: {
      int64_t x = a->data.i;
      lua_pushnumber(L, x);
      lua_pushboolean(L, x > DBL_MAX || x < DBL_MIN);
      break;
    }
    default:
      luaL_error(L, "Error in " LUA_QS ": datatype %d is not supported.", "ints.tonumber", a->datatype);
  }
  return 2;
}


