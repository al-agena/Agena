static uint64_t reverseu64 (uint64_t a) {
  uint64_t result = 0ULL;
  int i;
  /* Loop through all 64 bits sequentially */
  for (i = 0; i < 64; ++i) {
    /* Shift the current result left by one bit */
    result <<= 1;
    /* Take the LSB of the input 'a' and set it as the MSB of the result */
    result |= (a & 1ULL);
    /* Shift the input 'a' right to process the next bit */
    a >>= 1;
  }
  return result;
}

