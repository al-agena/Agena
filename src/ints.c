/* Extracts the High (Most Significant) 32-bit part */
static uint32_t gethighu32 (uint64_t n64) {
  /* Right shift by 32 bits discards the low 32 bits, moving the high 32 bits into the lower position. */
  return (uint32_t)(n64 >> 32);
}

/* Extracts the Low (Least Significant) 32-bit part */
static uint32_t getlowu32 (uint64_t n64) {
  /* A simple cast or a bitwise AND with 0xFFFFFFFF (as a mask), ensures only the low 32 bits are kept. */
  return (uint32_t)(n64 & 0xFFFFFFFFULL);  /* 6.8.2 ULL stadardisation */
}

/* Extracts the High (Most Significant) 32-bit part of an int64_t */
static int32_t gethigh32 (int64_t n64) {
  /* 1. Cast to uint64_t for a safe, logical (zero-filling) right shift. */
  /* 2. Right shift by 32 bits to move the high pattern to the low position. */
  /* 3. Cast the final 32-bit pattern back to an int32_t. */
  return (int32_t)((uint64_t)n64 >> 32);
}

static int32_t getlow32 (int64_t n64) {
  /* 1. Bitwise AND with an unsigned 64-bit mask (0xFFFFFFFFULL) to isolate the low 32 bits. */
  /* 2. The mask is applied to the int64_t. */
  /* 3. The final 32-bit pattern is cast to an int32_t. */
  return (int32_t)(n64 & 0xFFFFFFFFULL);  /* 6.8.2 ULL stadardisation */
}

/* Reassembles the two 32-bit parts back into a 64-bit integer */
static uint64_t reassemble_64 (uint32_t high_32, uint32_t low_32) {
  /* 1. Cast the high part to 64-bit to prevent overflow during the shift.
     2. Left shift the high part by 32 bits to put it back in place.
     3. Bitwise OR the result with the low part. */
  return ((uint64_t)high_32 << 32) | low_32;
}

