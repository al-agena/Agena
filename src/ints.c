/* Checks **********************************************************************************/

static Ints *aux_checkint (lua_State *L, int idx) {
  if (isints(L, idx)) {
    /* do nothing */
  } else if (agn_isnonnegint(L, idx)) {
    createuint64(L, agn_tonumber(L, idx));
    lua_replace(L, idx);
  } else if (agn_isstring(L, idx)) {
    int rc;
    uint64_t x = safe_str_to_uint64(agn_tostring(L, idx), &rc);
    if (rc)
      luaL_error(L, "Error: string is malformed or value is out-of-range.");
    createuint64(L, x);  /* 6.3.4 fix */
    lua_replace(L, idx);
  } else {  /* 6.3.5 */
    luaL_error(L, "Error: expected an " LUA_QS " userdata, non-negative integer or string.", "ints");
  }
  return (Ints *)lua_touserdata(L, idx);
}


/* Userdata generation *********************************************************************/

static void createbitwiseintfromdouble (lua_State *L, char what, double value, const char *procname) {
  Ints *a;
  luaL_checkstack(L, 2, "not enough stack space");  /* for numarray userdata and its registry aux table */
  a = (Ints *)lua_newuserdata(L, sizeof(Ints));
  a->datatype = what;
  switch (what) {
    case UINT64T: {
      a->data.ui = double2bitwiseuint64(value);
      agn_setutypestring(L, -1, "uint64");
      break;
    }
    case INT64T: {
      a->data.i = double2bitwiseint64(value);
      agn_setutypestring(L, -1, "int64");
      break;
    }
    default: {
      agn_poptop(L);
      luaL_error(L, "Error in " LUA_QS ": datatype %d does not exist.", procname, what);
    }
  }
  lua_setmetatabletoobject(L, -1, "ints", 0);
  lua_createtable(L, 0, 0);  /* set internal status table */
  lua_setfenv(L, -2);
}

