/* Generated by Gemini AI, public domain */
static int safe_int64_to_string (int64_t num, char *buffer, size_t buffer_size, int *rc) {
  /* PRId64 expands to the correct format specifier for int64_t (e.g., "lld" or "ld" depending on the system). */
  int result = snprintf(buffer, buffer_size, "%" PRId64, num);
  if (result < 0) {  /* encoding error or other system issue */
    buffer[0] = '\0';  /* ensure buffer is empty or 0-terminated */
    *rc = -1;
  } else if ((size_t)result >= buffer_size) {  /* output was truncated (buffer was too small) */
    *rc = 1;
  } else {
    *rc = 0;
  }
  return result;
}

/* Generated by Gemini AI, public domain */
static int safe_uint64_to_string (uint64_t num, char *buffer, size_t buffer_size, int *rc) {
  /* PRIu64 expands to the correct format specifier for uint64_t
     (e.g., "llu" or "lu" depending on the system) for UNSIGNED decimal output. */
  int result = snprintf(buffer, buffer_size, "%" PRIu64, num);
  if (result < 0) {
    buffer[0] = '\0';
    *rc = -1;
  } else if ((size_t)result >= buffer_size) {  /* buffer was too small and output was truncated */
    *rc = 1;
  } else {
    *rc = 0;
  }
  return result;
}


