static int64_t cbrt_i64 (int64_t v) {
  if (v == 0) return 0;
  if (v < 0) return -cbrt_i64(-v);
  /* Hardened initial guess for ARM/x86 */
  /* We ensure the bit count is divided by 3 BEFORE shifting */
  uint64_t x = (uint64_t)1 << ((64 - __builtin_clzll((uint64_t)v))/3 + 1);
  uint64_t y;
  while (1) {
    y = (2*x + (uint64_t)v/(x*x))/3;
    if (y >= x) return (int64_t)x;
    x = y;
  }
}

