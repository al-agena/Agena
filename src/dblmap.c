static int dblmap_new (lua_State *L) {
  khash_t(dblmap) **ht;
  size_t size = (size_t)tools_nextpow2u32(agnL_optposint(L, 1, 8));
  ht = (khash_t(dblmap) **)lua_newuserdata(L, sizeof(khash_t(dblmap) *));
  *ht = kh_init(dblmap);
  if (*ht == NULL) {
    agn_poptop(L);
    luaL_error(L, "Error in " LUA_QS ": memory allocation failed.", "dblmap.new");
  }
  kh_resize(dblmap, *ht, size);
  lua_setmetatabletoobject(L, -1, AGENA_DBLMAPLIBNAME, 1);
  lua_createtable(L, 0, 0);
  lua_setfenv(L, -2);
  return 1;
}


static int dblmap_getitem (lua_State *L)  {
  int nargs = lua_gettop(L);
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.getitem");
  }
  if (nargs == 1)  {
    lua_getfenv(L, 1);
  } else {
    luaL_checkstack(L, 2, "not enough stack space");
    if (agn_isnumber(L, 2))  {
      lua_Number key = agn_tonumber(L, 2);
      khint_t k = kh_get(dblmap, h, key);
      if (k != kh_end(h))  {
        lua_pushnumber(L, kh_val(h, k));
      } else  {
        lua_pushnil(L);
      }
    } else  {
      luaL_error(L, "Error in " LUA_QS ": invalid second argument given.", "dblmap.getitem");
    }
  }
  return 1;
}


static int dblmap_include (lua_State *L) {
  int rc;
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  double key = (double)agn_checknumber(L, 2);
  double val = (double)agn_checknumber(L, 3);
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.include");
  }
  khint_t k = kh_put(dblmap, h, key, &rc);
  if (rc == -1) {
    luaL_error(L, "Error in " LUA_QS ": memory allocation failed.", "dblmap.include");
  }
  kh_val(h, k) = val;
  lua_pushboolean(L, rc);
  return 1;
}


static int dblmap_purge (lua_State *L) {
  int rc = 0;
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  lua_Number key = agn_checknumber(L, 2);
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.purge");
  }
  int shrink = agnL_optboolean(L, 3, 0);
  khint_t k = kh_get(dblmap, h, key);
  if (k != kh_end(h)) {
    kh_del(dblmap, h, k);
    rc = 1;
  }
  if (rc && shrink) {
    kh_resize(dblmap, h, kh_size(h));
  }
  lua_pushboolean(L, rc);
  return 1;
}


static int aux_has (khash_t(dblmap) *h, double x) {
  int rc = 0;
  if (h) {
    khint_t k;
    for (k = kh_begin(h); k != kh_end(h) && !rc; ++k) {
      if (kh_exist(h, k)) {
        double d = kh_val(h, k);
        if (x == d) {
          rc = 1;
        }
      }
    }
  }
  return rc;
}

static int dblmap_has (lua_State *L) {
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  double x = agn_checknumber(L, 2);
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.has");
  }
  lua_pushboolean(L, aux_has(h, x));
  return 1;
}


static int dblmap_resize (lua_State *L) {
  int rc = 1;
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  if (!h) {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.resize");
  } else {
    khint_t old_buckets = h->n_buckets;
    khint_t target_buckets = (khint_t)agn_checknonnegint(L, 2);
    khint_t actual_target = 1;
    while (actual_target < target_buckets) {
      actual_target <<= 1;
    }
    if (actual_target < old_buckets) {
      actual_target = old_buckets;
    }
    if (actual_target != old_buckets) {
      kh_resize(dblmap, h, actual_target);
      rc = (h->n_buckets != old_buckets);
    } else {
      rc = 0;
    }
  }
  luaL_checkstack(L, 2, "not enough stack space");
  lua_pushboolean(L, rc);
  lua_pushnumber(L, (lua_Number)h->n_buckets);
  return 2;
}


static int dblmap_cleanse (lua_State *L) {
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.cleanse");
  } else {
    kh_clear(dblmap, h);
  }
  return 0;
}


static int iterate (lua_State *L) {
  kh_dblmap_t **ht = lua_touserdata(L, lua_upvalueindex(1));
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  khint_t k = (khint_t)lua_tointeger(L, lua_upvalueindex(2));
  if (h->n_buckets == 0 || k >= kh_end(h) ) {
    lua_pushnil(L);
    return 1;
  }
  luaL_checkstack(L, 3, "not enough stack space");
  for (; k != kh_end(h); ++k) {
    if (kh_exist(h, k)) {
      lua_pushnumber(L, (lua_Number)kh_key(h, k));
      lua_pushnumber(L, (lua_Number)kh_val(h, k));
      lua_pushinteger(L, (int)k + 1);
      lua_replace(L, lua_upvalueindex(2));
      return 2;
    }
  }
  lua_pushnil(L);
  return 1;
}

static int dblmap_iterate (lua_State *L) {
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  luaL_checkstack(L, 2, "not enough stack space");
  lua_pushvalue(L, 1);
  (void)h;  /* silences the unused variable warning */
  lua_pushinteger(L, (int)kh_begin(h));
  lua_pushcclosure(L, &iterate, 2);
  return 1;
}


/* Counts how many times khash.h has to resolve collisions by moving to the next slot (probing).
   Created by Gemini AI, 7.7.11 */
static uint32_t khash_collisions (kh_dblmap_t *h) {
  uint32_t collision_moves = 0;
  khint_t k;
  /* kh_end(h) is the total number of buckets currently allocated in the table array */
  khint_t mask = h->n_buckets - 1; 
  /* Loop through every physical bucket slot in the hash table */
  for (k = kh_begin(h); k < kh_end(h); ++k) {
    /* Check if the current slot actually contains a valid inserted element */
    if (kh_exist(h, k)) {
      double key = kh_key(h, k);
      /* 1. Calculate the raw hash value using your hash function */
      khint_t raw_hash = __kh_double_hash(key);
      /* 2. Calculate the "ideal" starting bucket slot khash intended to use */
      khint_t ideal_slot = raw_hash & mask;
      /* 3. If its current slot (k) is not its ideal slot, it was moved! */
      if (k != ideal_slot) collision_moves++;
    }
  }
  return collision_moves;
}

static int dblmap_attrib (lua_State *L) {
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  size_t n_occupied = h ? kh_size(h) : 0;
  size_t n_capacity = h ? h->n_buckets : 0;
  size_t n_empty = 0;
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.attrib");
  }
  khint_t k;
  for (k = kh_begin(h); k != kh_end(h); ++k) {
    if (!kh_exist(h, k)) {
      n_empty++;
    }
  }
  size_t n_void = (n_capacity > n_occupied + n_empty) ? (n_capacity - n_occupied - n_empty) : 0;
  lua_createtable(L, 0, 6);
  lua_rawsetstringnumber(L, -1, "count", (double)n_occupied);
  lua_rawsetstringnumber(L, -1, "capacity", (double)n_capacity);
  lua_rawsetstringnumber(L, -1, "empty", (double)n_empty);
  lua_rawsetstringnumber(L, -1, "void", (double)n_void);
  double cap = (double)n_capacity;
  lua_rawsetstringnumber(L, -1, "loadfactor", cap == 0.0 ? 0.0 : (double)n_occupied / cap);
  lua_rawsetstringnumber(L, -1, "utilization", cap == 0.0 ? 0.0 : (double)(n_occupied + n_empty) / cap);
  lua_rawsetstringnumber(L, -1, "collisions", khash_collisions(h));
  return 1;
}


static int dblmap_totable (lua_State *L)  {
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  if (!h)  {
    luaL_error(L, "Error in " LUA_QS ": uninitialized hash map.", "dblmap.totable");
  }
  lua_createtable(L, (int)kh_size(h), 0);
  khint_t k;
  for (k=kh_begin(h); k != kh_end(h); ++k)  {
    if (kh_exist(h, k))  {
      lua_pushnumber(L, (lua_Number)kh_key(h, k));
      lua_pushnumber(L, (lua_Number)kh_val(h, k));
      lua_rawset(L, -3);
    }
  }
  return 1;
}


static int dblmap_hash (lua_State *L) {
  double x = agn_checknumber(L, 1);
  khint_t n = agnL_optuint32_t(L, 2, 0);
  unsigned int l = lua_hashnum(x);   /* internally used by dblhash */
  khint_t h = __kh_double_hash(x);   /* originally proposed by Gemini AI */
  khint_t m = mixed_double_hash(x);  /* Fib hash proposed by Gemini AI */
  luaL_checkstack(L, 3, "not enough stack space");
  lua_pushnumber(L, (n != 0) ? l % n : l);
  lua_pushnumber(L, (n != 0) ? h % n : h);
  lua_pushnumber(L, (n != 0) ? m % n : m);
  return 3;
}


