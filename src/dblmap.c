static int mt_notin (lua_State *L)  {
  kh_dblmap_t **ht = checkdblmap(L, 2);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  double val = agn_checknumber(L, 1);
  lua_pushboolean(L, !aux_has(h, val));
  return 1;
}


static int mt_u2string (lua_State *L) {  /* at the console, the hash table is formatted as follows: */
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  if (agn_getutype(L, 1)) {
    lua_pushfstring(L, "(%u)", h ? kh_size(h) : 0);
    lua_concat(L, 2);
  } else
    luaL_error(L, "Error in " LUA_QS ": invalid number hash table.", "dblmap.__tostring");
  return 1;
}


static int mt_gc (lua_State *L)  {
  kh_dblmap_t **ht = checkdblmap(L, 1);
  kh_dblmap_t *h = (ht && *ht) ? *ht : NULL;
  if (h)  {
    *ht = NULL;  /* 7.7.10 fix */
    kh_destroy(dblmap, h);
  }
  agn_udfreeze(L, 1, 0);
  lua_setmetatabletoobject(L, 1, NULL, 1);
  lua_pushnil(L);
  lua_setfenv(L, 1);
  return 0;
}


