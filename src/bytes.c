/* Modular exponentiation (a^b % mod), avoiding overflow */
/* Uses the mulmod32 function defined above */
static uint32_t powmod32 (uint32_t base, uint32_t expo, uint32_t mod) {
  uint32_t res = 1UL;
  if (mod == 0UL) return 0UL;
  base %= mod;
  while (expo > 0UL) {
    if (expo & 1UL) res = mulmod32(res, base, mod); /* Use mulmod32 or mulmod32_fast */
      base = mulmod32(base, base, mod); /* Use mulmod32 or mulmod32_fast */
      expo >>= 1UL;
  }
  return res;
}

