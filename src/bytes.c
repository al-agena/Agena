/* Modular multiplication (a*b % mod), using 64-bit intermediate */
static uint32_t mulmod32 (uint32_t a, uint32_t b, uint32_t mod) {
  if (mod == 0UL) return 0UL;
  /* The product (a * b) can be up to (2^32 - 1)^2 which fits in uint64_t. */
  uint64_t res = (uint64_t)a * (uint64_t)b;
  return (uint32_t)(res % mod);
}

