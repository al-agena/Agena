#ifndef BIT
#define BIT(nr)         (1UL << (nr))
#endif

#ifndef BIT_ULL
#define BIT_ULL(nr)     (1ULL << (nr))
#endif

#define xint32divmod(t,n,d) { \
  t q, mask; \
  q = 0; r = 0; \
  if (!d) { \
    n = 0; \
    r = 0; \
  } else if (d == 2) { \
    r = n & 1; \
    n >>= 1; \
  } else if (d == 16) { \
    r = n & 0xf; \
    n >>= 4; \
  } else if ((uint32_t)n <= 0xffffffff) { \
    t u = n; \
    r = u % d; \
    n = u / d; \
  } else { \
    for (mask = BIT_ULL(31); mask; mask >>= 1) { \
      r <<= 1; \
      if (n & mask) r |= 1; \
      if (r >= d) { \
        r -= d; \
        q |= mask; \
      } \
    } \
    n = q; \
  } \
}

