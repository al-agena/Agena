static int bytes_numwords (lua_State *L) {  /* 2.10.0 */
  uint32_t hx, lx;  /* numrange is [0, 4294967295] */
  int32_t ux;  /* 2.17.1 fix */
  lua_Number x = agn_checknumber(L, 1);
  int inhex = agnL_optboolean(L, 2, 0);  /* 6.7.8 extension */
  luaL_checkstack(L, 3, "not enough stack space");  /* 6.7.8 fix */
  /* Unsigned 4-byte integers can be fully represented by C doubles. */
  EXTRACT_WORDS(hx, lx, x);
  lua_pushnumber(L, hx);
  if (inhex) agnL_pushhex(L, -1, 0);
  lua_pushnumber(L, lx);
  if (inhex) agnL_pushhex(L, -1, 0);
  ux = ((hx >> 20) & 0x7ff) - 0x3ff;  /* unbiased exponent, equals math.exponent(bytes_numhigh(x)) - 1, except 0 -> -1023,  2.16.11 */
  lua_pushnumber(L, ux);
  return 3;
}


