/* suffix.dump (filename, text, sa_bin [, lcp_bin]) -> boolean; generated by Gemini AI, 7.9.1 */
static int suffix_save (lua_State *L) {
  const char *filename = luaL_checkstring(L, 1);
  size_t text_len, sa_bytes, lcp_bytes = 0;
  const char *text = luaL_checklstring(L, 2, &text_len);
  const char *sa_bin = luaL_checklstring(L, 3, &sa_bytes);
  const char *lcp_bin = luaL_optlstring(L, 4, NULL, &lcp_bytes);
  /* Alignment sanity checks before writing (Safe to use luaL_error here) */
  if (sa_bytes != text_len * sizeof(saidx_t))
    return luaL_error(L, "Error in " LUA_QS ": suffix array size mismatches text length.", "suffix.save");
  if (lcp_bin && lcp_bytes != text_len * sizeof(saidx_t))
    return luaL_error(L, "Error in " LUA_QS ": LCP Array size mismatches text length.", "suffix.save");
  FILE *f = fopen(filename, "wb");
  if (!f) {
    /* Safe error handling: return false and an error string to Lua instead of crashing */
    lua_pushboolean(L, 0);
    lua_pushstring(L, "cannot open file for writing.");
    return 2; 
  }
  /* 1. Write file header signature */
  if (fwrite(SUFFIX_MAGIC, 1, 8, f) != 8) goto write_error;
  /* 2. Write component size lengths */
  uint64_t sizes[3];
  sizes[0] = (uint64_t)text_len;
  sizes[1] = (uint64_t)sa_bytes;
  sizes[2] = (uint64_t)lcp_bytes;
  if (fwrite(sizes, sizeof(uint64_t), 3, f) != 3) goto write_error;
  /* 3. Write raw payload data streams */
  if (text_len > 0 && fwrite(text, 1, text_len, f) != text_len) goto write_error;
  if (sa_bytes > 0 && fwrite(sa_bin, 1, sa_bytes, f) != sa_bytes) goto write_error;
  if (lcp_bin && lcp_bytes > 0) {
    if (fwrite(lcp_bin, 1, lcp_bytes, f) != lcp_bytes) goto write_error;
  }
  fclose(f);
  return 0;
write_error:
  fclose(f); /* Guaranteed cleanup of system file descriptor */
  luaL_error(L, "Error in " LUA_QS ": disk write failed or device out of space.", "suffix.save");
  return 0;
}


/* suffix.read (filename) -> text, sa_bin, lcp_bin (or nil); generated by Gemini AI, 7.9.1 */
static int suffix_read (lua_State *L) {
  const char *filename = luaL_checkstring(L, 1);
  FILE *f = fopen(filename, "rb");
  if (!f)
    return luaL_error(L, "Error in " LUA_QS ": cannot open file for reading.", "suffix.read");
  /* 1. validate header magic */
  char magic[8];
  if (fread(magic, 1, 8, f) != 8 || memcmp(magic, SUFFIX_MAGIC, 8) != 0) {
    fclose(f);
    return luaL_error(L, "Error in " LUA_QS ": index file format is invalid or signature corrupted.", "suffix.read");
  }
  /* 2. read component size lengths */
  uint64_t sizes[3];
  if (fread(sizes, sizeof(uint64_t), 3, f) != 3) {
    fclose(f);
    return luaL_error(L, "Error in " LUA_QS ": reading size metadata header failed.", "suffix.read");
  }
  size_t text_len  = (size_t)sizes[0];
  size_t sa_bytes  = (size_t)sizes[1];
  size_t lcp_bytes = (size_t)sizes[2];
  /* 3. Determine maximum layout buffer upfront to avoid variable array realloc risks */
  size_t max_buf = text_len;
  if (sa_bytes > max_buf)  max_buf = sa_bytes;
  if (lcp_bytes > max_buf) max_buf = lcp_bytes;
  /* Safe workspace buffer allocation */
  char *buffer = (char *)malloc(max_buf > 0 ? max_buf : 1);
  if (!buffer) {
    fclose(f);
    return luaL_error(L, "Error in " LUA_QS ": memory allocation failed.", "suffix.read");
  }
  luaL_checkstack(L, 3, "not enough stack space");
  /* read and push Text string */
  if (text_len > 0) {
    if (fread(buffer, 1, text_len, f) != text_len) goto load_error;
    lua_pushlstring(L, buffer, text_len);
  } else {
    lua_pushliteral(L, "");
  }
  /* read and push SA binary block */
  if (sa_bytes > 0) {
    if (fread(buffer, 1, sa_bytes, f) != sa_bytes) goto load_error;
    lua_pushlstring(L, buffer, sa_bytes);
  } else {
    lua_pushliteral(L, "");
  }
  /* read and push LCP binary block if it exists */
  if (lcp_bytes > 0) {
    if (fread(buffer, 1, lcp_bytes, f) != lcp_bytes) goto load_error;
    lua_pushlstring(L, buffer, lcp_bytes);
  } else {
    lua_pushnil(L);  /* return null for the missing LCP slot */
  }
  free(buffer);
  fclose(f);
  return 3; /* returns: text, sa_bin, lcp_bin */
load_error:
  free(buffer);
  fclose(f);
  return luaL_error(L, "Error in " LUA_QS ": unexpected end-of-file or corrupted data block.", "suffix.read");
}


