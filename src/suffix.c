#define SA_SIZE sizeof(saidx_t)  /* element sizing */

/* 1. Generic Suffix Array Generator, 7.9.0, created by Gemini AI */
static int suffix_sa (lua_State *L) {
  size_t len;
  const unsigned char *str = (const unsigned char *)luaL_checklstring(L, 1, &len);
  if (len == 0) {
    lua_pushliteral(L, "");
    return 1;
  }
  if (len > (size_t)(-1)/SA_SIZE) {
    luaL_error(L, "Error in " LUA_QS ": string size exceeds maximum capacity for indexing.", "suffix.sa");
  }
  /* Allocate memory for the suffix array buffer */
  saidx_t *SA = (saidx_t *)malloc(len*SA_SIZE);
  if (!SA)
    return luaL_error(L, "Error in " LUA_QS ": memory allocation failed.", "suffix.sa");
  if (divsufsort(str, SA, (saidx_t)len) != 0) {
    free(SA);
    luaL_error(L, "Error in " LUA_QS ": libdivsufsort computation failed.", "suffix.sa");
  }
  /* Push the raw integer bytes back to Lua as an immutable binary block */
  lua_pushlstring(L, (const char *)SA, len*SA_SIZE);
  free(SA);
  return 1;
}

/* 2. Generic LCP Array Generator (O(N) Kasai Algorithm), 7.9.0, created by Gemini AI */
static int suffix_lcp (lua_State *L) {
  size_t len, sa_len, i;
  const unsigned char *str = (const unsigned char *)luaL_checklstring(L, 1, &len);
  const saidx_t *SA = (const saidx_t *)luaL_checklstring(L, 2, &sa_len);
  if (len == 0 || sa_len != len*SA_SIZE) {
    return luaL_error(L, "Error in " LUA_QS ": string, suffix array lengths mismatch alignment.", "suffix.lcp"); 
  }
  if (len > (size_t)(-1)/SA_SIZE) {
    luaL_error(L, "Error in " LUA_QS ": libdivsufsort computation failed.", "suffix.lcp");
  }
  /* allocate temporary Inverse Suffix Array (ISA) and the output LCP array */
  saidx_t *ISA = (saidx_t *)malloc(len*SA_SIZE);
  saidx_t *LCP = (saidx_t *)malloc(len*SA_SIZE);
  if (!ISA || !LCP) {
    free(ISA); free(LCP);
    luaL_error(L, "Error in " LUA_QS ": storage allocation failed for LCP pipeline.", "suffix.lcp");
  }
  /* invert Suffix Array: ISA[SA[i]] = i */
  for (i=0; i < len; i++) {
    ISA[SA[i]] = (saidx_t)i;
  }
  /* Kasai's algorithm to compute LCP in linear time */
  saidx_t k = 0;
  for (i=0; i < len; i++) {
    if (ISA[i] == (saidx_t)(len - 1)) {
      k = 0;
      continue;
    }
    size_t j = (size_t)SA[ISA[i] + 1];
    while (i + k < len && j + k < len && str[i + k] == str[j + k]) {
      k++;
    }
    LCP[ISA[i]] = k;
    if (k > 0) k--;
  }
  LCP[len - 1] = 0; /* Boundary terminator */
  /* push the raw integer bytes back to Lua */
  lua_pushlstring(L, (const char *)LCP, len*SA_SIZE);
  free(ISA);
  free(LCP);
  return 1;
}


static int aux_search (const char *text, size_t text_len, 
                       const saidx_t *SA, size_t sa_elements,
                       const char *pattern, size_t pat_len, 
                       size_t start_offset, int case_insensitive,
                       size_t *out_best_idx) {
  /* 7.9.1, generated by Gemini AI */
  if (text_len == 0 || pat_len == 0 || start_offset > text_len) return 0;
  saidx_t low = 0;
  saidx_t high = (saidx_t)sa_elements - 1;
  saidx_t match_mid_idx = -1;
  saidx_t i;
  /* Step 1: Binary search for any structural match */
  while (low <= high) {
    saidx_t mid = low + (high - low)/2;
    saidx_t text_idx = SA[mid];
    size_t suffix_len = text_len - (size_t)text_idx;
    size_t cmp_len = (suffix_len < pat_len) ? suffix_len : pat_len;
    int cmp = case_insensitive ? strncasecmp(pattern, text + text_idx, cmp_len)
                               : memcmp(pattern, text + text_idx, cmp_len);
    if (cmp == 0) {
      if (pat_len > cmp_len) {
        low = mid + 1;
      } else {
        match_mid_idx = mid;
        break;
      }
    } else if (cmp < 0) {
      high = mid - 1;
    } else {
      low = mid + 1;
    }
  }
  /* Step 2: Linear neighborhood scan for the earliest occurrence >= start_offset */
  if (match_mid_idx != -1) {
    saidx_t best_text_idx = -1;
    for (i=match_mid_idx; i >= 0; i--) {
      saidx_t text_idx = SA[i];
      int match = case_insensitive ? (strncasecmp(pattern, text + text_idx, pat_len) == 0)
                                   : (memcmp(pattern, text + text_idx, pat_len) == 0);
      if (text_len - (size_t)text_idx >= pat_len && match) {
        if ((size_t)text_idx >= start_offset) {
          if (best_text_idx == -1 || text_idx < best_text_idx) best_text_idx = text_idx;
        }
      } else { break; }
    }
    for (i=match_mid_idx + 1; i < (saidx_t)sa_elements; i++) {
      saidx_t text_idx = SA[i];
      int match = case_insensitive ? (strncasecmp(pattern, text + text_idx, pat_len) == 0)
                                   : (memcmp(pattern, text + text_idx, pat_len) == 0);
      if (text_len - (size_t)text_idx >= pat_len && match) {
        if ((size_t)text_idx >= start_offset) {
          if (best_text_idx == -1 || text_idx < best_text_idx) best_text_idx = text_idx;
        }
      } else { break; }
    }
    if (best_text_idx != -1) {
      *out_best_idx = (size_t)best_text_idx;
      return 1;  /* match found */
    }
  }
  return 0;  /* no match */
}


